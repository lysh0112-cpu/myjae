/* 정관이 정한 대의원 수와 실제 명단이 맞는가.
   ★ 제24조 ② 100인 이상 120인 이하.
     명단이 이 범위를 벗어나면 정족수 다툼거리가 된다. */
function ruleOrgCheck(decKind){
  const o = RULEBOOK.org[decKind]; if(!o) return null;
  const n = (typeof decBaseFromRoster !== "undefined") ? decBaseFromRoster(decKind) : 0;
  if(!n) return {n:0, ok:false, why:"명단이 비어 있습니다."};
  if(n < o.min) return {n, ok:false,
    why:`정관은 ${o.min}인 이상으로 정하고 있습니다 (${o.art}). ${o.min - n}분 모자랍니다.`};
  if(n > o.max) return {n, ok:false,
    why:`정관은 ${o.max}인 이하로 정하고 있습니다 (${o.art}). ${n - o.max}분 많습니다.`};
  return {n, ok:true, why:`정관이 정한 ${o.min}~${o.max}인 안에 있습니다 (${o.art}).`};
}
