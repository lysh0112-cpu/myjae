/* 조합원 질문에서 찾는다. 지어내지 않고 자리만 짚는다. */
function arcFind(q){
  const s = (typeof hubNorm !== "undefined")
    ? hubNorm(q) : String(q||"").normalize("NFC").trim();
  if(!s) return [];
  const out = [];
  const pool = ARC_DOCS.filter(d => d.state === "verified")
    .concat((typeof LAW_DOCS!=="undefined"?LAW_DOCS:[])
      .filter(d => d.state !== "hidden").map(d => Object.assign({}, d, {cat:"law"})));
  pool.forEach(d => {
    /* ① 직원이 확인한 자리에서 찾는다
       ★★★ 확인한 것만 쓴다 (2026-08-22 밤) ★★★
         AI 초안은 ok 가 붙기 전까지 **없는 것과 같다.**
         쪽수가 틀린 채 나가면 조합원이 열었을 때 엉뚱한 데가 나오고
         「다알아가 틀렸다」가 된다. 답까지 틀리면 되돌릴 수 없다.

         직원이 손으로 적으신 옛 자료는 ok 칸이 없다.
         목차를 보고 적으신 것이므로 그대로 쓴다. */
    (d.index || []).forEach(ix => {
      if(!ix.q) return;
      if(ix.by === "ai" && !ix.ok) return;
      /* 물으실 말 + 직원이 더한 낱말 둘 다 본다.
         조합원은 "상한용적률이 얼마나 올랐나요" 라고 안 치신다. "용적률" 이라 치신다. */
      const pool = [ix.q].concat(ix.kw || []);
      const hit = pool.some(w => w && (s.indexOf(w) >= 0
        || w.split(/\s+/).some(t => t.length > 1 && s.indexOf(t) >= 0)));
      if(hit) out.push({doc:d, at:ix.at||"", page:ix.page||"",
                        why:ix.q, ans:ix.a||"", by:ix.okBy||""});
    });
    /* ② 제목에서 찾는다 */
    if(!out.some(o => o.doc.id === d.id)){
      const t = (d.title||"") + " " + (d.sub||"");
      const w = s.split(/\s+/).filter(x => x.length > 1);
      if(w.some(x => t.indexOf(x) >= 0)) out.push({doc:d, at:"", page:"", why:"제목"});
    }
  });
  return out.slice(0, 6);
}

