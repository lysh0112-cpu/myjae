/* 맞은 낱말 중 가장 긴 것의 길이 — 구체적인 쪽이 이긴다 */
function hitLen(words, s){
  /* 찾히는 쪽(낱말)도 골라야 한다. 한쪽만 고르면 여전히 못 찾는다. */
  const N = (typeof hubNorm !== "undefined")
    ? hubNorm : (v => String(v||"").normalize("NFC").trim());
  let n = 0;
  (words||[]).forEach(w0 => {
    const w = N(w0);
    if(!w) return;
    /* 질문 안에 낱말이 있거나, 짧게 물으셔서 낱말 안에 질문이 든 경우
       예 · "사업시행계획"으로 물으시면 "사업시행계획서"도 찾는다 */
    const hit = s.indexOf(w) >= 0
      || (s.length >= 3 && w.length >= s.length && w.indexOf(s) >= 0);
    if(hit && w.length > n) n = Math.min(w.length, s.length + 2);
  });
  return n;
}

