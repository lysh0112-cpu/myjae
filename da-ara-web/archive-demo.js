function acctPubData(){
  expFix(); budSync();
  const paid = EXPENSE.filter(x=>x.status === "paid");
  const wait = EXPENSE.filter(x=>x.status !== "paid");
  const used = {}, cnt = {}, plan = {};
  BUDGET.forEach(k=>{ used[k] = 0; cnt[k] = 0; plan[k] = 0; });
  paid.forEach(x=>{ if(used[x.item] === undefined){ used[x.item]=0; cnt[x.item]=0; }
    used[x.item] += x.amount; cnt[x.item] += 1; });
  wait.forEach(x=>{ if(plan[x.item] === undefined) plan[x.item] = 0;
    plan[x.item] += x.amount; });

  const r = budRev();
  return {
    updated: new Date().toISOString().slice(0,10),
    year: BUDGET_YEAR,
    basis: r ? {ord:r.ord, kind:r.kind, date:r.date, meet:r.meet, agenda:r.agenda} : null,
    revs: budList().map(v=>{ const d = budDiff(v);
      return {ord:v.ord, kind:v.kind, date:v.date, meet:v.meet, agenda:v.agenda,
              note:v.note||"", total:budTotalOf(v.plan), gap: d ? d.gap : null}; }),
    budget: Object.assign({}, BUDGET_PLAN),
    used, cnt, plan,
    /* ★ 건별은 네 칸뿐이다. 거래처는 아예 넘기지 않는다. */
    items: paid.slice()
      .sort((a,b)=>(b.paid||"").localeCompare(a.paid||""))
      .map(x=>({d:x.paid, item:x.item, t:x.title, amt:x.amount}))
  };
}

