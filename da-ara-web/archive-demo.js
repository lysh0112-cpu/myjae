/* 조문까지 바로 가는 주소를 만든다 */
function lawUrl(l, art){
  const base = (l && l.url) || "";
  if(!base || !art) return base;
  return base.replace(/\/+$/,"") + "/" + art;
}

/* ★ 질문을 받아 어디에 답이 있는지 가려낸다.
     법이면 조문으로, 정관이면 정관으로, 아직이면 아직이라고 말한다.
     엉뚱한 데서 답을 만들어 내지 않는다. */
function askFind(q){
  const s = (typeof hubNorm !== "undefined")
    ? hubNorm(q) : String(q||"").normalize("NFC").trim();
  if(!s) return [];
  const pool = (typeof lawsFor !== "undefined") ? lawsFor()
    : (typeof LAWS !== "undefined" ? LAWS : []);
  const out = [];
  /* 가장 잘 맞는 것만 남긴다. 넓은 낱말이 끼어들면 답이 흐려진다. */
  const top = Math.max(...askAll().map(a => hitLen(a.w, s)), 0);
  askAll().forEach(a => {
    if(hitLen(a.w, s) < top || top === 0) return;
    if(a.t === "law"){
      const l = pool.find(x => x.id === a.id);
      if(!l) return;                        /* 이 구역에 적용 안 되는 조례 */
      if(out.some(o => o.law && o.law.id === l.id && o.art === a.art)) return;
      out.push({kind:"law", law:l, art:a.art||"",
                at:a.art || l.kind, sum:a.sum, url:lawUrl(l, a.art)});
    } else if(a.t === "rule"){
      const has = (typeof ARC_DOCS !== "undefined")
        ? ARC_DOCS.filter(d => d.cat === "rule" && d.state === "verified") : [];
      out.push({kind:"rule", sum:a.sum, docs:has});
    } else if(a.t === "fact"){
      out.push({kind:"fact", sum:a.sum, need:a.need || "조합 자료"});
    } else {
      out.push({kind:"later", sum:a.sum});
    }
  });
  /* 법령 이름을 그대로 물으신 경우 */
  if(!out.length) pool.forEach(l => {
    const key = l.name.replace(/\s/g,"");
    const qq  = s.replace(/\s/g,"");
    if(qq.length > 3 && (key.indexOf(qq) >= 0 || qq.indexOf(key) >= 0))
      out.push({kind:"law", law:l, art:"", at:l.kind, sum:l.note, url:l.url});
  });
  /* 같은 갈래는 하나만 남긴다 — 정관 · 아직은 여러 번 나올 필요가 없다 */
  const seen = {};
  return out.filter(o => {
    if(o.kind === "law") return true;
    if(seen[o.kind]) return false;
    seen[o.kind] = 1; return true;
  }).slice(0, 5);
}

