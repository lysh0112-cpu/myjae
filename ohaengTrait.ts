export const OHAENG_ORDER: Ohaeng[] = ['목', '화', '토', '금', '수']

/**
 * 서비스별로 어느 칸을 내보낼지 고른다.
 *   ★통제는 여기서 한다. 프롬프트로 막지 않는다. (교훈 BF)
 *     프롬프트는 어투·길이·형식을 맡고, 무엇을 아느냐는 재료가 정한다.
 *
 *   ★과다인지 아닌지는 **부르는 쪽**이 정해서 온다. 이 파일은 안 정한다.
 *     사주분석 쪽 :  if (grade(pts) === '과다') excessLines(el, who)
 *     진로적성 쪽 :  if (gradeOf(r, el).grade === '과다') excessLines(el, who)
 */
export type OhaengAudience = '성인' | '학생'

export function excessLines(el: Ohaeng, who: OhaengAudience): string[] {
  const row = OHAENG_TRAIT[el]
  return [
    ...row.excess,
    ...(who === '성인' ? row.excessAdult ?? [] : row.excessStudent ?? []),
  ]
}

export function developLines(el: Ohaeng): string[] {
  return OHAENG_TRAIT[el].develop
}
