import { useEffect, useState } from 'react'
import { fetchHomeFlags } from '@/lib/homeFlags'

export function useSisterLinks(): boolean {
  const [on, setOn] = useState(false)
  useEffect(() => {
    let alive = true
    fetchHomeFlags()
      .then(f => { if (alive) setOn(f.sisterLinks) })
      .catch(() => {})
    return () => { alive = false }
  }, [])
  return on
}
