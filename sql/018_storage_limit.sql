--  018_storage_limit.sql — 큰 파일을 받는다 (2026-09-16)
-- ───────────────────────────────────────────────────────────
--  ★ 왜 올리나
--
--    정보몽땅에 올라간 대의원회 회의자료가 **96MB** 였다.
--    지금 한도는 40MB 라 「파일이 너무 큽니다」로 막힌다.
--
--    ★ 정보몽땅 뷰어로는 원문을 제대로 읽을 수 없고
--      찾아보기(검색)도 안 된다. 링크만 걸어 두면
--      조합원이 실제로는 못 본다.
--
--    ★★★ 「자료가 있다」는 것 자체가 중요하다 ★★★
--      조합원이 실제로 여는 횟수와 상관없이,
--      **조합이 숨기지 않았다는 증거**가 된다.
--      나중에 다툴 때 「그건 자료실에 올라가 있습니다」로 끝난다.
--
--  ★★★ 이 SQL 만으로는 부족하다 (2026-09-16 고침) ★★★
--
--    버킷 한도를 200MB 로 올려도 **프로젝트 전체 한도**가 따로 있다.
--      Storage → Settings → Global file size limit
--
--    ★ Pro 라도 **지출 상한(spend cap)이 켜져 있으면 50MB 로 묶인다.**
--      상한을 끄면 500GB 까지 되지만, 그러면 전송량이 250GB 를 넘을 때
--      **요금이 그대로 붙는다.** 조합 돈이라 상한은 켜 둔 채로 간다.
--
--  ★ 그래서 조각으로 나눠 올린다
--
--    50MB 를 넘는 자료는 **45MB 씩 잘라** 보낸다.
--      → hub.js 의 hubUploadBig() · hubJoinParts()
--
--    ★★★ 쪼개는 것이 보는 사람을 불편하게 하면 안 된다 ★★★
--      조합원 화면에는 **한 줄로 보이고**, 내려받으시면
--      조각을 차례로 받아 **브라우저가 이어 붙인다.**
--      1/3 · 2/3 을 따로 받게 하면 쪼갠 뜻이 없다.
--
--  ★ 그래도 이 SQL 은 돌려 두는 편이 낫다.
--    나중에 지출 상한을 끄시게 되면 버킷 한도가 곧바로 쓰인다.
--
--  ★ 요금 — 저장 용량은 돈이다
--
--    Supabase Pro 는 저장 100GB 가 포함이고 그 위로는 종량이다.
--    96MB 짜리를 매주 올리면 1년에 5GB 다. 아직 여유가 있다.
--    다만 **회의자료를 매번 올리실 필요는 없다.**
--    의사록 · 속기록은 수백 KB 라 부담이 없다.
-- ═══════════════════════════════════════════════════════════

SET search_path = storage;

-- ── 버킷 한도를 200MB 로 ────────────────────────────────────
--  ★ 96MB 를 받되 여유를 둔다. 스캔 뜬 회의자료가 더 클 수 있다.
--  ★ 이 값은 **서버가 막는 마지막 자물쇠**다.
--    화면에서 한 번, hub.js 에서 한 번, 여기서 한 번 — 세 겹이다.
--    화면 검사만 있으면 개발자 도구로 얼마든지 넘길 수 있고,
--    저장 요금은 조합 것으로 나간다.
update storage.buckets
   set file_size_limit = 200 * 1024 * 1024
 where id = 'consent-scan';

-- 받는 파일 종류도 함께 넓힌다 (사진 · 한글 · 워드)
update storage.buckets
   set allowed_mime_types = array[
     'application/pdf',
     'image/jpeg', 'image/png',
     'application/haansofthwp', 'application/x-hwp', 'application/vnd.hancom.hwp',
     'application/haansofthwpx', 'application/vnd.hancom.hwpx',
     'application/msword',
     'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
   ]
 where id = 'consent-scan';

