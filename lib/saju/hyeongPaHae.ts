const ALL: RelRow[] = [...HYEONG, ...PA, ...HAE, ...WONJIN]

/** 두 지지로 찾는다 — 차례는 상관없습니다 */
export function findRel(a: string, b: string): RelRow[] {
  return ALL.filter(r => r.chars.length === 2 && r.chars.includes(a) && r.chars.includes(b))
}

/** 삼형이 섰는가 (세 글자가 다 있어야) */
export function findSamhyeong(branches: string[]): RelRow[] {
  return HYEONG.filter(r => r.chars.length === 3 && r.chars.every(c => branches.includes(c)))
}

/**
 * 나가는 줄을 고른다.
 *   ★통제는 여기서 한다. 프롬프트로 막지 않는다. (교훈 BF)
 *   ⚠️ original 은 어느 경우에도 안 나갑니다.
 *   ⚠️ 학생에게는 sayAdult 가 안 나갑니다. 몸·돈·인연 이야기가 거기 있습니다.
 */
export function relLines(r: RelRow, who: RelAudience): string[] {
  return [...r.say, ...(who === '성인' ? r.sayAdult ?? [] : [])]
}
