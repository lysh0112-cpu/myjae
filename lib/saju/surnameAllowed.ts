// ══════════════════════════════════════════════════════════════════
//  ⚠️ hanja 표에 «없는» 두 글자 — ★2026-08-09 대표님 지시
//     「辻(십)·鴌(궉)은 ★한자표와 관계없이 성씨 파일 한자에는 넣어라」
//     ⇒ 위 SURNAME_ALLOWED 에 «그대로 들어 있습니다» (십: 辻 · 궉: 鴌).
//     ⚠️ 다만 화면은 값을 hanja 표에서 꺼내 옵니다 —
//        ★표에 줄이 생기기 «전» 에는 화면에 안 나옵니다. 이 파일 탓이 아닙니다.
//        ⇒ _SQL_성씨_빠진두글자.sql 을 돌리시면 그때 나옵니다.
//     ⛔ 화면 쪽에서 없는 글자를 «지어내» 그리지 마십시오 —
//        획수·자원오행이 없어 수리 4격이 어긋납니다.
// ══════════════════════════════════════════════════════════════════

// ══════════════════════════════════════════════════════════════════
//  ★낱글자 목록 + 복성을 «접은» 것 — 이것이 실제로 쓰이는 표입니다
//
//   ⛔⛔ 손으로 적지 마십시오. 위 두 표에서 «코드가» 만듭니다.
//      ⇒ 엑셀이 바뀌면 위 두 표만 다시 만들면 여기는 따라옵니다.
//   ⚠️ 복성 낱글자는 «뒤에» 붙입니다 — 흔한 단성이 앞에 서야 하기 때문입니다.
//      (「남」이면 南 이 먼저, 「고」면 高·固·顧 다음에 孤)
// ══════════════════════════════════════════════════════════════════
const MERGED: Record<string, string[]> = (() => {
  const out: Record<string, string[]> = {}
  for (const [g, v] of Object.entries(SURNAME_ALLOWED)) out[g] = [...v]
  for (const [hg, hj] of Object.entries(SURNAME_COMPOUND)) {
    const sounds = [...hg]
    const chars = [...hj]
    if (sounds.length !== chars.length) continue   // ⚠️ 소리와 글자 수가 어긋나면 건너뜁니다
    sounds.forEach((s, i) => {
      const c = chars[i]
      if (!out[s]) out[s] = []
      if (!out[s].includes(c)) out[s].push(c)
    })
  }
  return out
})()

/**
 * 그 소리에 «보일» 성씨 한자들.
 *
 * ⚠️ 빈 배열이면 «그 소리는 목록에 없다» 는 뜻입니다.
 *    ★그때 부르는 쪽이 어떻게 할지는 아래 shouldFilterSurname 이 정합니다.
 */
export function surnameAllowedOf(hangul: string): string[] {
  return MERGED[(hangul ?? '').trim()] ?? []
}

/** 그 한자가 이 소리의 성씨 칸에 «보여도 되는가» */
export function isSurnameAllowed(hangul: string, hanja: string): boolean {
  return surnameAllowedOf(hangul).includes((hanja ?? '').trim())
}

/**
 * ★이 소리에 거르기를 «걸어도 되는가».
 *
 * 🔴 목록에 그 소리가 «아예 없으면» 거르지 «않습니다».
 *    [왜]  거르면 그 손님은 성씨 한자를 하나도 못 골라 ★다음으로 넘어가지 못합니다.
 *          귀화하신 분·드문 본관이 그렇습니다. 막으면 그 집안이 아예 못 씁니다.
 *    ⚠️ 「0이면 전체를 보여 주는」 되돌림이 아닙니다 —
 *       목록에 «있는» 소리는 0이 되지 않습니다. 없는 소리만 그냥 지나갑니다.
 *    ⛔ 이 문을 닫으려면 대표님께 먼저 여쭈십시오.
 */
export function shouldFilterSurname(hangul: string): boolean {
  return surnameAllowedOf(hangul).length > 0
}
