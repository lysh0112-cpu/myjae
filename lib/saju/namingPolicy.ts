/**
 * ★한 번 조회로 지어 볼 수 있는 이름 개수.
 *
 * ⚠️ 이 값을 3 으로 되돌리면 «예전 그대로» 돕니다. 다른 곳은 안 고쳐도 됩니다.
 *    (관리자 설정에서 내려오던 값도 아래 clampTryLimit 을 지납니다)
 */
export const NAMES_PER_LOOKUP = 1

/** 한 번에 하나만 보는가 */
export const isSingleName = NAMES_PER_LOOKUP <= 1

/**
 * 관리자 설정에서 내려온 회차 한도를 «정책에 맞게» 다듬습니다.
 *
 * ⚠️ 화면마다 따로 판단하면 한 군데만 빠뜨려도 어긋납니다.
 *    ★한도를 쓰는 곳은 «모두» 이 함수를 지나게 하십시오.
 */
export function clampTryLimit(fromSettings: number | null | undefined): number {
  const n = Number(fromSettings)
  const raw = Number.isFinite(n) && n > 0 ? n : 3
  return isSingleName ? NAMES_PER_LOOKUP : raw
}

/**
 * 결과 화면에 보여 줄 이름들.
 *
 *   하나만 보는 정책이면 «가장 마지막에 지은 것» 하나만 냅니다.
 *   ⚠️ 앞의 것을 «지우지» 않습니다 — 보여 주지 않을 뿐입니다.
 *      기록은 보관함에 그대로 남아 있고, 손님은 거기서 다 보실 수 있습니다.
 */
export function visibleTries<T>(all: T[]): T[] {
  if (!isSingleName) return all
  return all.length ? [all[all.length - 1]] : []
}

/**
 * ★옛 손님이 이미 쌓아 둔 기록이 있는가.
 *
 * ⚠️ 있으면 «보관함에서 볼 수 있다» 고 알려 드려야 합니다.
 *    말없이 감추면 「내가 지은 이름 어디 갔지」가 됩니다.
 */
export function keepPastTries(all: unknown[]): number {
  return isSingleName ? Math.max(0, all.length - 1) : 0
}
