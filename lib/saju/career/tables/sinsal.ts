/** 판정 방식 */
export type SinsalKind =
  | 'char'    // 글자 하나하나를 센다 (현침·탕화·도화지지·역마지지)
  | 'pair'    // 지지 두 글자가 짝을 이뤄야 성립 (귀문관살·천문성)
  | 'pillar'  // 간지 한 기둥이 통째로 맞아야 성립 (백호·괴강·양인)
  | 'double'  // 같은 글자가 둘 이상 (丙丙·戊戊·庚庚·戌戌·壬壬·癸癸)

export interface SinsalRow {
  key: string
  name: string
  hanja: string
  kind: SinsalKind[]
  /** kind 'char' 로 셀 글자 */
  chars?: string[]
  /** 준(準)으로 치는 글자 — 세되 절반의 무게로 본다 */
  semi?: string[]
  /** kind 'pair' 의 지지 짝 */
  pairs?: Array<[string, string]>
  /** kind 'pillar' 의 간지 (천간+지지) */
  pillars?: string[]
  /** kind 'double' 의 글자 (2개 이상이면 성립) */
  doubles?: string[]
  /** 이 개수 이상이면 작용력이 있다고 본다 */
  threshold: number

  // ══════════════════════════════════════════════════════════════
  //  ★2026-08-02 — 신살의 «자리» 조건 (교재 48·72·94~97·181쪽 전수 확인)
  //
  //   [무엇이 있었나]  이 표는 «글자와 개수» 만 셌습니다. 자리를 안 봤습니다.
  //     ⇒ 년지의 子 하나로도 도화가 잡혔습니다.
  //        교재 48쪽은 「年支와 時支에 있으면 도화가 아니다」라고 합니다.
  //
  //   ⚠️ 신살마다 «다릅니다». 하나로 뭉뚱그리지 마십시오 —
  //     도화     성립 자체가 月支·日支에서만 (48쪽)
  //     괴강·양인·지망  月 > 日 > 時 > 年 (95·96쪽) — «세되 무게가 다름»
  //     천을귀인  ★日, 時 > 年, 月 (96쪽) — «거꾸로» 입니다
  //     백호     ★자리 조건이 «없습니다» (95쪽 전문 확인). 붙이지 마십시오
  //     역마·화개·천문성·문창성  자리 조건 «교재에 없음»
  // ══════════════════════════════════════════════════════════════

  /**
   * ★이 자리에 있어야만 «성립» 한다. 없으면 자리를 안 봅니다.
   *   교재 48쪽 도화살 — "年支와 時支에 있으면 도화가 아니다"
   */
  onlyAt?: Array<'년주' | '월주' | '일주' | '시주'>
  /**
   * ★이 자리 가운데 «적어도 하나» 는 걸려야 작용한다.
   *   교재 94쪽 도화살 — "月支, 日支 포함 2개 이상"
   *   ⚠️ onlyAt 과 다릅니다 — 이건 «개수를 세는 조건» 입니다.
   */
  needAt?: Array<'년주' | '월주' | '일주' | '시주'>
  /**
   * 자리별 «무게» — 세되 강약을 가릅니다. 화면 문구에만 씁니다.
   *   교재 95·96쪽 "月 > 日 > 時 > 年의 순으로 작용력이 있음"
   *   ⚠️ 큰 수가 «센» 자리입니다. 없으면 무게를 말하지 않습니다.
   */
  posWeight?: Partial<Record<'년주' | '월주' | '일주' | '시주', number>>
  /** ★개수가 «많으면» 좋지 않다 — 교재 96쪽 "귀인은 1~2개가 좋다" */
  bestCount?: [number, number]
  /**
   * 여럿을 한 덩어리로 세는 경우의 묶음 이름.
   * ★교재 93쪽은 백호·괴강·양인을 (5)번 한 항목으로 묶고
   *   "2~3개 이상 있으면 기운이 크고 승부욕이 강하여" 라고 한다.
   *   따로 세면 각각 1개로 성립해 버려 신살이 과하게 뜬다.
   */
  group?: string
  /** 기질 — 고객에게 전할 말 */
  gijil: string
  /** 진로적성 — 어울리는 직업 */
  jobs: string[]
  /** 살펴야 할 점 — ★화면에 그대로 나간다. 겁주지 않게 쓸 것 */
  caution: string
  /** 교재 원문 (근거 보존용). 화면에 절대 내보내지 않는다 */
  srcCaution?: string
  src: string
}

