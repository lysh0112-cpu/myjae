// ── 학생에게는 보이지 않을 직업 ────────────────────────────────
//
// ★교재 목록에는 유흥업·카지노·대부업 같은 것이 그대로 들어 있다.
//   명리 기록으로는 지울 이유가 없지만, **학생 모드에서는 아이 사주를
//   부모가 함께 읽는다.** 아이에게 권할 자리가 아니다.
//   성인에게는 그대로 보이고, 학생에게만 걸러 낸다.
export const ADULT_ONLY = new Set([
  '유흥업', '유흥주점', '술집', '주류업', '바텐더', '카지노',
  '대부업', '고리대금업', '사채업', '투기업', '전당포',
  '도축업', '장의사', '무속인', '목욕탕', '안마사',
])

/** 학생에게 보여도 되는 직업인가 */
export function okForStudent(key: string): boolean {
  return !ADULT_ONLY.has(key)
}

const STRIP = /(관련업|관련직|계통|계열|분야|사업)$/

/** 이름을 맞춰 주는 열쇠. 화면에 쓰지 말고 비교에만 쓸 것. */
export function jobKey(raw: string): string {
  let x = raw.replace(/[\s()]/g, '')
  if (x.length > 3) x = x.replace(STRIP, '')
  return JOB_ALIAS[x] ?? x
}

/** 열쇠 → 화면에 보일 이름 */
export function jobLabel(key: string): string {
  return JOB_DISPLAY[key] ?? key
}
