//
//   GWA 배열이 비어 있는 동안 gyeyeol.ts 는 학과를 한 줄도 내보내지
//   않습니다. 그러므로 이 파일을 이대로 올려도 화면은 지금과 똑같습니다.
//   자료가 들어오면 아래 규칙대로 행만 채우면 곧바로 살아납니다.
//
// ─────────────────────────────────────────────────────────────────
// ★옮길 때 지킬 것
//
//  ① 오행 태그는 교재가 붙여 둔 것만 넣는다
//     교재 132~139쪽은 학과마다 오행을 달아 두었다. 진로적성 자료 가운데
//     오행 태그가 살아 있는 유일한 곳이다. 없는 학과에 우리가 달지 않는다.
//       사범계열(水)        → el: ['수']
//       일어일문학과(木火)   → el: ['목', '화']
//
//  ② 계열(lean)은 교재가 밝힌 경우에만 적는다
//     안 밝혔으면 비워 둔다. gyeyeol.ts 가 오행으로 어림잡는다.
//     (목화 → 인문 / 금수 → 자연 / 화가 뚜렷하면 예체능. 교재 129쪽)
//
//  ③ 이름은 교재 표기 그대로
//     "일어일문학과" 를 "일본어학과" 로 고치지 않는다. 검수 때 대조가 안 된다.
//     다만 OCR 잔재(쪽번호 끼어듦·문장 꼬리 붙음)는 반드시 걷어낸다.
//       예 "역 121 술인" → "역술인" 같은 사고가 ilju.ts 에서 13건 나왔다.
//
//  ④ 근거 쪽수를 반드시 단다 (교훈 BE)
//     연재쌤은 tables/ 만 보시면 되게 한다.
//
//  ⑤ 대학은 학과와 성격이 다르다
//     교재가 대학 이름을 직접 대응시켰다면 UNIV 쪽에 따로 담는다.
//     학교 이름을 사주로 찍어 주는 것은 조심스러운 일이라,
//     연재쌤·대표님 확인 전에는 화면에 내보내지 않는다.
// ─────────────────────────────────────────────────────────────────

import type { Ohaeng } from '../types'

export type GwaLean = '인문' | '자연' | '예체능'

export interface GwaRow {
  /** 학과·계열 이름. 교재 표기 그대로 (화면에 이대로 나간다) */
  name: string
  /** 교재가 붙인 오행 태그 1~2개 */
  el: Ohaeng[]
  /** 교재가 계열을 밝힌 경우만. 없으면 비워 둔다 */
  lean?: GwaLean
  /** 근거 쪽수 — 예 '교재 134쪽' */
  src: string
}

/**
 * 학과 표 (교재 132~139쪽)
 *
 * ⛔ 비어 있음. 채우기 전까지 학과는 화면에 안 나갑니다.
 *
 * 채울 때 형식:
 *   { name: '사범계열',     el: ['수'],        lean: '인문', src: '교재 134쪽' },
 *   { name: '일어일문학과', el: ['목', '화'],  lean: '인문', src: '교재 135쪽' },
 */
export const GWA: GwaRow[] = []

/** 화면에 보여 줄 학과 개수 (대표님 지시 2026-07-27 — 5~7개) */
export const GWA_SHOW = 6

/** 이 점수를 넘어야 후보로 본다 */
export const GWA_MIN = 2

export const GWA_SRC = '교재 132~139쪽 「10. 학생 진로 적성」'

/** 표가 채워졌는가. 비어 있으면 판정이 학과를 통째로 건너뛴다. */
export const HAS_GWA = () => GWA.length > 0
