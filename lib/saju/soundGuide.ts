export interface SoundGuide {
  /** 한 낱말 주제 — 교재의 격 이름과 해설에서 뽑았습니다 */
  theme: string
  /** 건설적 한 문장 — AI 가 이 어조로 풀어 씁니다 */
  gentle: string
  /** ★손님·AI 에게 내보내도 되는 격 이름. 자극적이면 null 입니다 */
  gyeokPublic: string | null
}

/** 격 이름을 손님 앞에 내도 되는가 */
export function isGyeokPublishable(gyeok: string): boolean {
  return !GYEOK_HARSH_WORDS.some((w) => gyeok.includes(w))
}

