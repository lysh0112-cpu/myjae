export type Eumyang = '음' | '양'

/**
 * ★교재 46쪽 — 「숫자적으로 1, 3, 5, 7, 9 홀수는 양이고 2, 4, 6, 8, 10 짝수는 음이다」
 *   → 획수 홀짝이 «정본» 입니다.
 */
export function eumyangOfStrokes(strokes: number): Eumyang {
  return strokes % 2 === 0 ? '음' : '양'
}

/**
 * ★★교재 48쪽에는 «모음» 으로 가르는 축도 함께 실려 있습니다.
 *     양  ㅏ ㅑ ㅗ ㅛ
 *     음  ㅓ ㅕ ㅜ ㅠ ㅡ ㅣ
 *
 * ⚠️⚠️ 현행 코드는 «획수만» 봅니다. 이 축은 «쓰지 않고 있습니다».
 *    교재가 「좋은 음양 배열」을 ●○ 로만 그려 두고 그 ●○ 가 획수인지 모음인지
 *    밝히지 않았습니다. 46쪽이 「숫자적으로」라 못 박았으므로 획수로 읽었습니다.
 *    ★연재쌤 확인 대상입니다 — 모음 축도 볼 것인가?
 *
 * ⚠️ 표에 없는 모음이 있습니다 (ㅐ ㅔ ㅚ ㅟ ㅢ ㅘ ㅝ …). 교재가 안 다룹니다.
 *    아래는 «표에 있는 것만» 답하고 나머지는 null 입니다. 지어내지 않습니다.
 */
export const EUMYANG_JUNGSEONG: Readonly<Record<string, Eumyang>> = {
  ㅏ: '양', ㅑ: '양', ㅗ: '양', ㅛ: '양',
  ㅓ: '음', ㅕ: '음', ㅜ: '음', ㅠ: '음', ㅡ: '음', ㅣ: '음',
}

const JUNGSEONG = [
  'ㅏ','ㅐ','ㅑ','ㅒ','ㅓ','ㅔ','ㅕ','ㅖ','ㅗ','ㅘ','ㅙ','ㅚ',
  'ㅛ','ㅜ','ㅝ','ㅞ','ㅟ','ㅠ','ㅡ','ㅢ','ㅣ',
] as const

/** 완성형 한글 한 글자의 중성. 아니면 null */
export function jungseongOf(han: string): string | null {
  const c = han.charCodeAt(0) - 0xac00
  if (!Number.isFinite(c) || c < 0 || c > 11171) return null
  return JUNGSEONG[Math.floor((c % 588) / 28)]
}

/** ★모음으로 본 음양. 교재 표에 없는 모음이면 null (지어내지 않습니다) */
export function eumyangOfVowel(han: string): Eumyang | null {
  const j = jungseongOf(han)
  return j ? (EUMYANG_JUNGSEONG[j] ?? null) : null
}

