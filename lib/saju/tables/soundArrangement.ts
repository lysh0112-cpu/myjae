/**
 * ★교재를 관통하는 규칙 (125칸 중 116칸 = 96.7% 가 이대로입니다)
 *
 *    상극이 «하나라도» 있으면        → 흉
 *    상극이 없고 상생이 있으면       → 길
 *    비화만 이어지면                → 오행마다 다릅니다 (규칙 없음)
 *
 *  ⚠️ 규칙에서 벗어나는 «예외» 네 칸 — 표를 고칠 때 지우지 마십시오
 *      목화화  상생1·상극0 인데 «반길반흉»  (고목봉춘격)
 *      화목토  상생1·상극1 인데 «길»        (만화방창격)
 *      토목화  상생1·상극1 인데 «반길반흉»  (운중지월격)
 *      수토금  상생1·상극1 인데 «반길반흉»  (선고후안격)
 *
 *  ⚠️ 비화만 다섯 칸 — 계산으로 나오지 않습니다. 표를 그대로 쓰십시오
 *      목목목 길 · 화화화 흉 · 토토토 반길반흉 · 금금금 흉 · 수수수 흉
 *
 *  ★그래서 이것은 «식» 이 아니라 «표» 입니다. 계산하지 말고 찾아 쓰십시오.
 */
export function lookupArrangement(a: string, b: string, c: string): SoundArrangement | null {
  return SOUND_ARRANGEMENT[a + b + c] ?? null
}

