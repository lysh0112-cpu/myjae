export type ChungAudience = '성인' | '학생'

/** 충 이름으로 찾는다 — 예) findChung('子午沖') */
export function findChung(key: string): ChungRow | undefined {
  return JIJI_CHUNG.find(r => r.key === key)
}

/** 두 지지로 찾는다 — 차례는 상관없습니다 */
export function findChungByChars(a: string, b: string): ChungRow | undefined {
  return JIJI_CHUNG.find(r => r.chars.includes(a) && r.chars.includes(b))
}

/**
 * 나가는 줄을 고른다.
 *   ★통제는 여기서 한다. 프롬프트로 막지 않는다. (교훈 BF)
 *   ⚠️ alias 와 original 은 어느 경우에도 안 나갑니다.
 *   ⚠️ 학생에게는 몸·돈·부부 이야기가 안 나갑니다.
 */
export function chungLines(key: string, who: ChungAudience): string[] {
  const r = findChung(key)
  if (!r) return []
  return [...r.say, ...(who === '성인' ? r.sayAdult ?? [] : [])]
}

/** 천간충인가 (칠충) */
export function isCheonganChung(a: string, b: string): boolean {
  return CHEONGAN_CHUNG.some(k => k.includes(a) && k.includes(b))
}
