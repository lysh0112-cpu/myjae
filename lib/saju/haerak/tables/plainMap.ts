/** 갈래 이름 — 표에 없으면 ★원문 그대로 (지어내지 않습니다) */
export function plainWho(who: string): string {
  return WHO_PLAIN[who]?.plain ?? who
}

/** 본문 — 넷이 «다» 맞을 때만 갈아끼웁니다. 아니면 ★원문 그대로 */
export function plainText(no: number, hyo: number, who: string, src: string): string {
  const hit = TEXT_PLAIN.find(r => r.no === no && r.hyo === hyo && r.who === who && r.src === src)
  return hit ? hit.plain : src
}

/** 검사·검수용 — 아직 «제 초안» 인 줄만 */
export function draftRows(): { where: string; src: string; plain: string }[] {
  const out = Object.entries(WHO_PLAIN)
    .filter(([, v]) => v.by === '초안')
    .map(([k, v]) => ({ where: '갈래 이름', src: k, plain: v.plain }))
  for (const r of TEXT_PLAIN) {
    if (r.by === '초안') out.push({ where: `${r.no}괘 ${r.hyo}효`, src: r.src, plain: r.plain })
  }
  return out
}
