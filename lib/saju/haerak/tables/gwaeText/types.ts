/**
 *  하락이수 2단계 — 괘 풀이 글을 담는 ★틀
 *  2026-09-14 (8부)
 *
 *  ┌──────────────────────────────────────────────────────────────────┐
 *  │  ⛔⛔ ★글을 «지어내지» 마십시오.                                   │
 *  │     여기 들어가는 글은 «전부» 교재에서 온 것이라야 합니다.          │
 *  │     한 글자도 제가 고쳐 쓰지 않았습니다 (src 그대로).              │
 *  │     ⇒ 다듬은 말이 필요하면 ★따로 칸을 만드십시오 (신살 표 방식).    │
 *  └──────────────────────────────────────────────────────────────────┘
 *
 *  ★쓰는 칸은 «세 개» 뿐입니다 — 동효가 1·2·3 밖에 안 나오기 때문입니다.
 *     4·5·6효는 ⛔ 담지 않습니다. 책에 있어도 «영영 안 쓰입니다».
 *
 *  ★괘마다 «파일 하나» 입니다 (g10-sa.ts 처럼).
 *     ⇒ 봉투를 나눠 드려도 서로 «안 부딪힙니다». 64개를 한 파일에 몰면
 *       한 글자 고칠 때마다 온 파일이 흔들립니다.
 */

/** 한 갈래 — 「벼슬한 사람은 …」 한 덩이 */
export interface GwaePart {
  /** 갈래 이름 — ★교재 말 그대로 (「벼슬한 사람」 · 「선비」 · 「일반인」 · 「수가 흉한 사람」 …) */
  who: string
  /** 그 갈래에 붙은 글 — ★교재 원문 그대로 */
  text: string
}

/** 한 효 */
export interface HyoText {
  /**
   *  효 이름 — 初六 · 九二 · 六三 …
   *  ★하괘의 음양으로 «정해지는» 값입니다 (양이면 九 · 음이면 六).
   *  ⇒ 검사가 이것을 하괘와 대조합니다. 어긋나면 남의 괘 글이 섞인 것입니다.
   */
  label: string
  /**
   *  ⚠️ ★교재에 «적혀 있던» 효 이름 — label 과 «다를 때만» 넣습니다.
   *     ⛔ 교재를 고치지 않고 «둘 다» 남기는 자리입니다 (신살 표의 srcGijil 과 같은 결).
   *     ⇒ 연재쌤께 「교재가 맞습니까 셈이 맞습니까」 여쭐 근거가 됩니다.
   */
  labelSrc?: string
  /**
   *  갈래 이름 «없이» 통으로 시작하는 앞머리.
   *  ⚠️ 師 六三 처럼 「슬픔과 근심이 많이 생기며…」 로 먼저 나오는 자리가 있습니다.
   */
  lead?: string
  /** 갈래별 글 — ★교재 차례 그대로 */
  parts: GwaePart[]
}

/** 한 괘 */
export interface GwaeText {
  /** 하락이수 도표 번호 (GWAE_NO 와 «같아야» 합니다 — 검사가 대조합니다) */
  no: number
  /** 괘 이름 (한자) */
  name: string
  /** 동효 1·2·3 — ⛔ 4·5·6은 담지 않습니다 */
  hyo: { 1: HyoText; 2: HyoText; 3: HyoText }
  /** 교재 어디서 왔는지 — ★근거를 남깁니다 (연재쌤 검수에 씁니다) */
  src: string
  /**
   *  🔴 ★제가 «손글씨를 잘 못 읽은» 자리.
   *     ⛔ 비워 두지 마십시오 — 모르는 것을 «모른다» 고 적는 칸입니다.
   *     ⇒ 대표님이 이 자리만 눈으로 대조해 주시면 됩니다.
   */
  check?: string[]
}
