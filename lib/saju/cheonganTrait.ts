/** 천간 차례 */
export const CHEONGAN_ORDER: string[] = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸']

export type Gender = '남' | '여'

/**
 * 나가는 줄을 고른다.
 *   ★통제는 여기서 한다. 프롬프트로 막지 않는다. (교훈 BF)
 *   ⚠️ 성별 줄은 gender 를 넘길 때만 나갑니다. 안 넘기면 안 나갑니다.
 *      궁합처럼 상대방을 말하는 자리에서는 안 넘기시는 편이 낫습니다.
 */
export function cheonganLines(stem: string, gender?: Gender): string[] {
  const r = CHEONGAN_TRAIT[stem]
  if (!r) return []
  return [
    ...r.traits,
    ...r.advice,
    ...(gender ? r.sayByGender?.[gender] ?? [] : []),
  ]
}

/** 41~42쪽 쪽만 따로 꺼낸다 (풀이·성품·개운법) */
export function cheongan41(stem: string): { image: string; nature: string; tips: string[] } | null {
  const r = CHEONGAN_TRAIT[stem]
  return r ? { image: r.image, nature: r.nature41, tips: r.tips41 } : null
}
