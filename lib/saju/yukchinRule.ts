export function toJiName(pillar: string): string {
  return pillar.replace('주', '지')
}

const CHUNG_SET: ReadonlyArray<readonly [string, string]> = [
  ['子', '午'], ['丑', '未'], ['寅', '申'], ['卯', '酉'], ['辰', '戌'], ['巳', '亥'],
]

export function isChung(a: string, b: string): boolean {
  return CHUNG_SET.some(([x, y]) => (a === x && b === y) || (a === y && b === x))
}

export interface ChungHit {
  key: string
  a: PillarName
  b: PillarName
  rule: ChungPositionRule
}

/**
 * 원국에 선 沖을 자리와 함께. 영향력이 큰 것부터.
 *
 * ⚠️ 이 함수가 **jaryoPick.hapChungBrief 를 고칠 때 쓸 것**입니다.
 *    지금 hapChungBrief 는 saju.map(p => p.branch) 로 자리를 버립니다.
 */
export function chungInSaju(saju: Pillar[]): ChungHit[] {
  const out: ChungHit[] = []
  const seen = new Set<string>()
  for (let i = 0; i < saju.length; i++) {
    for (let j = i + 1; j < saju.length; j++) {
      const A = saju[i], B = saju[j]
      if (!A?.branch || !B?.branch) continue
      if (!isChung(A.branch, B.branch)) continue
      const rule = chungRuleOf(A.pillar, B.pillar)
      if (!rule) continue
      const key = `${A.branch}${B.branch}`
      if (seen.has(key)) continue
      seen.add(key)
      out.push({
        key: `${A.branch}${B.branch}沖`,
        a: A.pillar as PillarName, b: B.pillar as PillarName, rule,
      })
    }
  }
  return out.sort((x, y) => y.rule.weight - x.rule.weight)
}

/**
 * 손님에게 나갈 한 줄.
 *   ★「변동」인 沖은 좋다고 단정하지 않고 방향만 돌립니다.
 *   ★「부정」인 沖은 지금까지 나가던 chungMeaning 의 말을 그대로 씁니다.
 *     (그래서 이 함수는 부정 쪽에서 빈 문자열을 돌려주고,
 *      부르는 쪽이 chungMeaning 의 say 를 쓰게 둡니다)
 */
export function chungToneLine(hit: ChungHit): string {
  const where = `${toJiName(hit.a)}-${toJiName(hit.b)}`
  if (hit.rule.tone === '부정') return ''
  return `${hit.key}(${where}) — ${hit.rule.say}`
}

