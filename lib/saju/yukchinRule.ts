/**
 * 자리 짝 여섯이 다 담겼는지, 「일지가 끼면 부정」 규칙과 맞는지 대조.
 * @returns 어긋난 것. 비어 있어야 정상입니다.
 */
export function verifyChungPosition(): string[] {
  const bad: string[] = []
  const seen = new Set<string>()
  for (let i = 0; i < 4; i++) {
    for (let j = i + 1; j < 4; j++) {
      const k = `${PILLAR_ORDER[i]}-${PILLAR_ORDER[j]}`
      seen.add(k)
      const r = CHUNG_POSITION.find(x => x.pair === k)
      if (!r) { bad.push(`${k} 규칙이 없습니다`); continue }
      const hasDay = k.includes('일주')
      const want: ChungTone = hasDay ? '부정' : '변동'
      if (r.tone !== want) bad.push(`${k} 는 ${want} 이어야 하는데 ${r.tone} 입니다`)
    }
  }
  for (const r of CHUNG_POSITION) {
    if (!seen.has(r.pair)) bad.push(`${r.pair} 는 자리 짝이 아닙니다`)
  }
  return bad
}

