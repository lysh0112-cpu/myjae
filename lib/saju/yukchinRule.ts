/** 자리 짝 이름을 차례대로 맞춘다 (년→월→일→시) */
export function pairKey(a: string, b: string): string {
  const ia = PILLAR_ORDER.indexOf(a as PillarName)
  const ib = PILLAR_ORDER.indexOf(b as PillarName)
  if (ia < 0 || ib < 0) return ''
  return ia <= ib ? `${a}-${b}` : `${b}-${a}`
}

export function chungRuleOf(a: string, b: string): ChungPositionRule | undefined {
  const k = pairKey(a, b)
  return CHUNG_POSITION.find(r => r.pair === k)
}

