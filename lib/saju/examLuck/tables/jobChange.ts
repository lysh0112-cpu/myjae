/**
 * 그 사람에게 맞는 조언을 고른다.
 * ★아무것도 안 걸려도 빈손으로 돌려주지 않는다. 교재가 못 박은 대목이기 때문이다.
 */
export function pickAdvice(hitKeys: string[]): JobChangeAdvice[] {
  const get = (k: JobChangeAdvice['key']) => JOB_CHANGE_ADVICE.find(a => a.key === k)!
  const out: JobChangeAdvice[] = []
  // 혼잡·도식·인성형충 → 일 자체가 바뀌는 결이라 가족과 뜻 모으기
  if (hitKeys.some(k => ['honjap', 'pyeoninDosik', 'woljiChung'].includes(k))) out.push(get('가족'))
  // 비겁 강해짐(스카우트·동업) → 팀으로
  if (hitKeys.includes('bigyeop')) out.push(get('함께'))
  // 움직임이 하나라도 잡히면 준비 이야기가 늘 앞선다
  if (hitKeys.length) out.unshift(get('준비'))
  if (!out.length) out.push(get('준비'))
  return out
}

