/**
 * ★인사 발표 달의 «두 달 앞» 이 눈여겨볼 달입니다.
 *   [왜] 발표는 12월이어도 «정해지는 것» 은 그 앞입니다.
 *        평가 자료가 오가는 때를 짚어야 손님이 «지금» 하실 일이 생깁니다.
 *   ⇒ 모르겠다 · 수시면 null — ★달을 짚지 않고 흐름만 말합니다.
 */
export function watchMonthOf(season?: string | null): number | null {
  const s = PROMO_SEASONS.find(x => x.key === season)
  if (!s || s.month == null) return null
  const m = s.month - 2
  return m <= 0 ? m + 12 : m
}

