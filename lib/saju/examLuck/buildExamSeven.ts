// ── ⚠️ 왜 «세 번 나눠» 부르는가 (교훈 CV — 지우지 마십시오) ────────────
//   한 번에 여러 대목을 시키면 AI 가 앞의 두셋만 길게 쓰고 뒤를 안 씁니다.
//   실제로 겪은 것을 그대로 적습니다.
//       여섯 대목 한 번  →  두셋만 씀
//       세 대목 한 번    →  첫 하나만 씀
//   프롬프트를 네 번 다듬어도 같은 자리에서 실패했습니다.
//   ★대목 수가 문제가 아니라 «여러 대목을 한 번에» 가 문제입니다.
//   그래서 일곱을 «2+2+3» 으로 나눕니다. 한 묶음이 둘셋이면 다 씁니다.
//
// ── ⚠️ 마크다운 헤더(###)가 아니라 ■ 를 씁니다 ────────────────────────
//   지시서는 «### 마크다운 헤더» 를 요구하지만, 이 저장소의 파서
//   (buildExamPrompt.parseExamTongbyeon) 는 `■ 제목` 을 기준으로 자릅니다.
//   ### 로 바꾸면 ①파서 ②보관함에 이미 저장된 옛 통변이 **둘 다** 깨집니다.
//   ★스트리밍·끊김 안전이라는 «뜻» 은 그대로이고 기호만 ■ 입니다.
//   ⚠️ 굳이 ### 로 가시려면 stripLead·isHeading 을 함께 고치고
//      옛 저장본 마이그레이션을 먼저 준비하십시오.
//   ★대신 지시서의 «이모지 + 번호» 는 제목에 그대로 넣었습니다.
//     화면에 그리는 제목은 SEVEN 표의 것이고, sevenKeyOf 가 이모지·번호를
//     떼고 맞추므로 AI 가 제목을 조금 흘려 써도 잡힙니다.
//
// ── ⚠️ 두 벌로 가른 까닭 (2026-07-30 대표님 지시) ─────────────────────
//   한 벌로 두고 target 으로 낱말만 바꾸던 때, 성인에게 «수시 정시 비율» 을
//   묻고 학생에게 «지원 전략» 을 어른 말로 쓰는 일이 생겼습니다.
//   갈래 «이름과 개수» 자체가 달라야 하는 자리였습니다.
//       진학  공부DNA · 과목 · 수시정시 · 12개월 · D-Day · 목표대학 · 학부모
//       취업  일의결 · 준비순서 · 시험:경력 · 12개월 · D-Day · 지원전략 · 맺음말
//   ★키(key)는 같게 두었습니다. 화면 코드가 갈래마다 갈리지 않게 하려고요.

