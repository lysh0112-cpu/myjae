//
// ⚠️ AI 가 제목을 조금 바꿔 써도 잡아야 합니다. (교훈 CY — 자리가 아니라 제목으로)
//   ★2026-07-30 — 제목에 이모지와 번호가 붙었으므로 그것을 먼저 떼어 냅니다.
//     안 떼면 「🧬 1. 타고난…」 과 「타고난…」 이 다른 것으로 잡혀
//     갈래가 통째로 안 그려집니다.

/** ■ · 이모지 · 번호 · 공백을 떼고 알맹이만 남긴다 */
function bareTitle(title: string): string {
  return title
    .replace(/^■\s*/, '')
    // 이모지·기호 — 한글·한자·영숫자가 아닌 앞머리를 떼어 냅니다
    .replace(/^[^\p{Script=Hangul}\p{Script=Han}A-Za-z0-9]+/u, '')
    .replace(/^\d+\s*[.)·]?\s*/, '')
    .replace(/\s/g, '')
    .trim()
}

