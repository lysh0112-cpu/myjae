/**
 * 그 한글 소리로 «성씨가 되는» 한자들.
 *
 * ⚠️ 없으면 «빈 배열» 을 돌려줍니다. 그때는 부르는 쪽이 hanja 표를 씁니다.
 *    ★여기에 없다고 «성씨가 아니다» 라고 말하지 마십시오. 이 표는 전부가 아닙니다.
 */
export function surnameHanjaOf(hangul: string): string[] {
  return SURNAME_HANJA[(hangul ?? '').trim()] ?? []
}

/** 그 한자가 이 소리의 «성씨» 로 쓰이는가 */
export function isSurnameHanja(hangul: string, hanja: string): boolean {
  return surnameHanjaOf(hangul).includes((hanja ?? '').trim())
}

/**
 * 성씨 차례로 줄 세우는 잣대.
 *
 *   ★성씨 한자를 앞으로, 그 안에서는 «흔한 차례» 로.
 *   ⚠️ 성씨가 아닌 한자를 «빼지 않습니다» — 뒤로 보낼 뿐입니다.
 *      드문 집안 글자가 이 표에 없을 수 있습니다.
 */
export function surnameRank(hangul: string, hanja: string): number {
  const i = surnameHanjaOf(hangul).indexOf((hanja ?? '').trim())
  return i === -1 ? 999 : i
}
