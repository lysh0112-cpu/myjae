/** 그 지지와 삼합을 이루는 셋 — ⛔ 못 찾으면 빈 배열 (지어내지 않습니다) */
export function samhapOf(ji: string): string[] {
  return SAMHAP.find(g => g.includes(ji)) ?? []
}
