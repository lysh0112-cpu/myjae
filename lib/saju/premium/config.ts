/** 결제 관문이 붙기 전 임시 — 모두에게 프리미엄 */
const PREMIUM_FOR_ALL = true

/**
 * 이 손님에게 프리미엄 리포트를 낼 것인가.
 *
 * @param paid 결제한 손님인가 (결제 모듈이 붙으면 이 값이 실제로 들어옵니다)
 *
 * ★결제가 붙으면 PREMIUM_FOR_ALL 을 false 로 두기만 하면 됩니다.
 *   그러면 paid === true 인 손님에게만 나갑니다.
 */
export function isPremium(paid?: boolean): boolean {
  return PREMIUM_FOR_ALL || !!paid
}
