export type SalAudience = '성인' | '학생'

/** 이름으로 찾는다 — 예) findSal('yangin') */
export function findSal(key: string): SalRow | undefined {
  return SAL_TABLE.find(r => r.key === key)
}

/**
 * 나가는 줄을 고른다.
 *   ★통제는 여기서 한다. 프롬프트로 막지 않는다. (교훈 BF)
 *   ⚠️ original 은 어느 경우에도 안 나갑니다.
 */
export function salLines(key: string, who: SalAudience): string[] {
  const r = findSal(key)
  if (!r) return []
  return [...r.say, ...(who === '성인' ? r.sayAdult ?? [] : [])]
}
