/** 어디까지 나가는가 — ⛔ 빠뜨리면 '상담사만' 으로 봅니다 (안전한 쪽) */
export type SomuTo = '둘다' | '상담사만'

/** 교재 한 줄 */
export interface SomuLine {
  /** ★교재 원문 그대로. 다듬지 마십시오. */
  text: string
  /** 어디까지 나가는가 — 없으면 '상담사만' */
  to?: SomuTo
}

/** 그림 프롬프트 — 교재 삽화를 «흉내내지» 않고 물상 낱말로 새로 그립니다 */
export interface SomuImage {
  /** 한 줄 설명 (상담사 화면에 보이는 말) */
  ko: string
  /** ★영어 프롬프트 — 화풍(STYLE_CONFIGS)은 여기 적지 «않습니다». 뒤에 붙습니다. */
  prompt: string
}

/** 천간 두 글자가 만난 자리 */
export interface SomuPair {
  /** 상대 천간 */
  with: string
  /** 교재 원문 줄들 */
  lines: SomuLine[]
  /** 그림 */
  img?: SomuImage
}

/** 계절 묶음 — 교재의 ㉮㉯㉰㉱ */
export type SomuSeasonKey = '寅卯辰' | '巳午未' | '申酉戌' | '亥子丑'

/** 사례 (通辯論) — ⛔ 전부 상담사만 */
export interface SomuCase {
  label: string
  /** 생년월일 표기 — 교재에 적힌 그대로 */
  birth: string
  /** 원국 여덟 글자 — 년월일시 차례가 «아니라» 교재 표기 차례(시일월년) */
  chart: string
  /** ★교재가 각 천간 위에 적어 둔 물상 낱말 (시일월년 차례) */
  words: string[]
  /** 대운 */
  daeun?: string
  lines: SomuLine[]
  img?: SomuImage
}

/** 일간 한 장 */
export interface SomuChapter {
  /** 일간 */
  stem: string
  /** 장 이름 — 甲木 */
  label: string
  /** 쪽수 — 출전 표기용 */
  pages: string
  /** 개관 — 물상 낱말 무리 */
  keywords: SomuLine[]
  /** 개관 — 죽 이어지는 설명 */
  intro: SomuLine[]
  /**
   * 좋아하는·싫어하는 天干 — ★물상론이 «일간만으로» 정해 둔 것
   * ⚠️⚠️ ★장마다 «있는 것이 아닙니다».
   *    甲木은 017쪽에 「좋아하는 天干 : 丙, 庚, 壬 / 싫어하는 天干 : 乙, 己, 辛」이
   *    딱 잘라 적혀 있으나, ★乙木 장에는 그런 목록이 «없습니다».
   *    ★庚金은 224쪽에 «있습니다» — 다만 교재가 「天干」이 아니라 「五行」이라 적어 두고
   *      천간 글자를 늘어놓았습니다 (좋아하는 甲乙丙丁戊壬 / 싫어하는 庚辛己癸).
   *    ⇒ 일곱 장 중 ★둘(甲木·庚金)에만 있습니다. 辛金 쪽에 또 나올 수 있습니다.
   * ⛔⛔ 없는 장에 ★«지어 넣지» 마십시오. 본문에서 «짐작해» 채우면
   *    교재가 하지 않은 판정을 저희가 하는 것이 됩니다.
   *    ⇒ 없으면 ★빈 배열로 두고, 화면은 그 묶음을 «통째로» 걸러냅니다.
   */
  likes: string[]
  dislikes: string[]
  /** 天干論 열 조합 */
  pairs: SomuPair[]
  /** 地支論 네 계절 */
  seasons: Record<SomuSeasonKey, SomuLine[]>
  /** 通辯論 사례 */
  cases: SomuCase[]
}

