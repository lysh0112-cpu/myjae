/** 손님에게도 나갈지 — somu/data.ts 의 to 와 같은 뜻입니다 (없으면 '상담사만') */
export type ByeonjeungTo = '둘다' | '상담사만';

/** ○ 줄 하나 — 원문 문장 + 그 아래 «공식» 줄 */
export type ByeonjeungRule = {
  /** 이 줄이 두고 말하는 일간 (교재가 안 밝힌 줄은 없음) */
  day?: string;
  /** 원문 문장 그대로 */
  text: string;
  /** 교재가 화살표로 적어 둔 «공식» 줄. 없는 줄도 있습니다 */
  formula?: string[];
  to?: ByeonjeungTo;
};

/** 예시 원국 상자 하나 — ★시일월년 차례 */
export type ByeonjeungCase = {
  /** '시/일/월/년' */
  chart: string;
  /** 십성 — 시일월년. 교재가 일부만 적은 상자가 있습니다 */
  tenGods: string[];
  /** 물상 낱말 — 시일월년. 교재가 적은 만큼만 */
  words: string[];
  /** ★두 줄로 적힌 상자의 «아랫줄» (413·415·419) */
  words2?: string[];
  /** 상자 오른쪽의 맺음말 */
  label: string;
  /** 상자 밖 ○ 줄에 맺음이 있는 경우 (子水) */
  note?: string;
};

export type ByeonjeungBranch = {
  branch: string;
  page: string;
  rules: ByeonjeungRule[];
  cases: ByeonjeungCase[];
  /** ※ 로 시작하는 총론 — ★戌土에만 있습니다 */
  summary?: string;
};

