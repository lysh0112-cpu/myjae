export type HyeongsangTo = '둘다' | '상담사만';

/** ○ 줄 하나 */
export type HyeongsangLine = {
  text: string;
  /** 「− 」로 이어지는 딸린 줄 */
  sub?: string[];
  to?: HyeongsangTo;
};

/** 예시 원국 상자 하나 — ★시일월년 차례 */
export type HyeongsangCase = {
  /** 교재 표기 그대로. 없는 상자도 있습니다 */
  birth?: string;
  /** 乾(남) / 坤(여) */
  gender?: '乾' | '坤';
  /** '시/일/월/년' */
  chart: string;
  /** 천간 «위» 물상 낱말 — 시일월년. 교재가 적은 만큼만 */
  stemWords: string[];
  /** 지지 «아래» 낱말 — 시일월년. 붙은 상자에만 */
  branchWords?: string[];
  /** ★나이 오름차순 (교재는 오른쪽부터 어린 나이라 뒤집었습니다) */
  daeun: string;
  lines: HyeongsangLine[];
  /** ⛔ 교재 삽화를 스캔해 넣지 마십시오. 물상 낱말로 «새로» 그립니다 */
  img?: string;
};

export type HyeongsangType = {
  name: string;
  page: string;
  /** 성립 조건 — 교재가 형상 이름 «바로 아래» 적은 줄 */
  condition: string[];
  /** ★조건이 «표로 떨어지는가» — 위 머리말 참조 */
  ruleLike: boolean;
  cases: HyeongsangCase[];
};

