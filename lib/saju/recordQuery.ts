/**
 *  보관함 목록 조회에 붙입니다 — ★「사람」 줄을 걷고 «결과 기록» 만 남깁니다.
 *
 *  쓰는 법
 *    let q = supabase.from('saju_records').select(...).eq('user_id', uid)
 *    q = onlyResultRows(q)
 *
 *  ⚠️ DB 에서 거릅니다 — 가져와서 거르지 않으므로 목록이 가볍습니다.
 *  ⛔ 「사람 고르기」 화면(PersonPickerModal)에는 ★쓰지 마십시오 —
 *     그쪽은 반대로 «사람» 만 봐야 합니다 (savedPeople 의 isResultRecord 가 맡습니다).
 */
export function onlyResultRows<Q extends { not: (col: string, op: 'is', val: null) => Q }>(q: Q): Q {
  return q.not('result_data', 'is', null)
}
