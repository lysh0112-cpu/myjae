const YANG_STEM = new Set(['甲', '丙', '戊', '庚', '壬'])
const BONGI: Record<string, string> = {
  子: '癸', 丑: '己', 寅: '甲', 卯: '乙', 辰: '戊', 巳: '丙',
  午: '丁', 未: '己', 申: '庚', 酉: '辛', 戌: '戊', 亥: '壬',
}

/** 그 십성이 사주에 몇 자인가 (천간 + 지지 본기) */
export function sipsinCount(c: SajuCtx, key: YukchinKey): number {
  if (!c.dayStem) return 0
  let n = 0
  for (const s of c.stems) if (s !== c.dayStem && sipsinOf(c.dayStem, s) === key) n++
  for (const b of c.branches) {
    const s = BONGI[b]
    if (s && sipsinOf(c.dayStem, s) === key) n++
  }
  return n
}

/** 그 짝이 사주에 몇 자인가 */
export function pairCount(c: SajuCtx, pair: YukchinPair): number {
  return YUKCHIN_KEYS
    .filter(k => PAIR_OF[k] === pair)
    .reduce((s, k) => s + sipsinCount(c, k), 0)
}

