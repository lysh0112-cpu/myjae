export const GWADA_CNT = 4

const many = (key: YukchinKey) => (c: SajuCtx) => sipsinCount(c, key) >= GWADA_CNT
const manyPair = (p: YukchinPair) => (c: SajuCtx) => pairCount(c, p) >= GWADA_CNT
const hasSipsin = (key: YukchinKey) => (c: SajuCtx) => sipsinCount(c, key) > 0
const at = (c: SajuCtx, where: 'year' | 'month' | 'day' | 'hour') =>
  where === 'year' ? c.yearBranch : where === 'month' ? c.monthBranch
    : where === 'day' ? c.dayBranch : c.hourBranch
/** 그 자리 지지가 이 십성인가 */
const branchIs = (where: 'year' | 'month' | 'day' | 'hour', key: YukchinKey) => (c: SajuCtx) => {
  const b = at(c, where); const s = BONGI[b]
  return !!(c.dayStem && s && sipsinOf(c.dayStem, s) === key)
}
/** 그 자리 지지가 이 짝인가 */
const branchIsPair = (where: 'year' | 'month' | 'day' | 'hour', p: YukchinPair) => (c: SajuCtx) => {
  const b = at(c, where); const s = BONGI[b]
  if (!c.dayStem || !s) return false
  const k = sipsinOf(c.dayStem, s) as YukchinKey
  return !!PAIR_OF[k] && PAIR_OF[k] === p
}
/** 간여지동 — 천간과 지지 본기가 같은 오행이며 같은 십성인 기둥이 있는가 */
const ganyeojidong = (c: SajuCtx) =>
  c.stems.some((s, i) => {
    const b = c.branches[i]
    return !!(s && b && BONGI[b] && sipsinOf(c.dayStem, s) === sipsinOf(c.dayStem, BONGI[b]))
  })
/** 양인격 — 양일간 + 月支 겁재 (교재 107쪽) */
const yanginGyeok = (c: SajuCtx) =>
  YANG_STEM.has(c.dayStem) && branchIs('month', '겁재')(c)
/** 관살혼잡 — 편관과 정관이 함께 */
const gwansalHonjap = (c: SajuCtx) => sipsinCount(c, '편관') > 0 && sipsinCount(c, '정관') > 0
/** 상관견관 — 상관과 정관이 함께 */
const sanggwanGyeongwan = (c: SajuCtx) => sipsinCount(c, '상관') > 0 && sipsinCount(c, '정관') > 0
/** 天干에 그 십성이 있는가 (년·월 자리) */
const stemAtYearMonth = (key: YukchinKey) => (c: SajuCtx) =>
  c.stems.slice(0, 2).some(s => !!s && sipsinOf(c.dayStem, s) === key)
/** 일간이 이 글자인가 */
const dayStemIs = (...ch: string[]) => (c: SajuCtx) => ch.includes(c.dayStem)

