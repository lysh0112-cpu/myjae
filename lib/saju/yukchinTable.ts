/**
 * 교재 106~115쪽 「기본 성향」 열(= 그 육친이 剋하는 자리)이
 * cheonganTrait.ts 의 tendency 와 맞는지 대조한다.
 *
 * 甲木 일간 기준으로 각 십성의 대표 천간을 잡고,
 * 그 천간이 剋하는 대상 중 음양이 같은 십성을 계산해
 * cheonganTrait 의 tendency 문구와 견준다.
 *
 * ⚠️ 오행 방향만 보면 편·정 둘이 나와 열 칸이 다 어긋난 것처럼 보입니다.
 *    음양까지 맞춰야 합니다. 2026-07-28 에 실제로 그렇게 잘못 짚었습니다.
 *
 * @returns 어긋난 칸. 비어 있어야 정상입니다.
 */
export function verifyGeuk(): Array<{ stem: string; fromTable: string; fromTrait: string }> {
  // 甲木 일간일 때 각 천간이 무슨 십성인가
  const STEMS = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸']
  const bad: Array<{ stem: string; fromTable: string; fromTrait: string }> = []
  for (const s of STEMS) {
    // s 를 일간 자리에 놓았을 때 s 가 剋하는 대상 중 음양이 같은 것 = s 의 편재
    const target = STEMS.find(o => sipsinOf(s, o) === '편재')
    if (!target) continue
    // 그것을 진짜 일간(甲) 기준 이름으로 바꾼다
    const name = s === '甲' ? '편재' : sipsinOf('甲', target)
    const trait = CHEONGAN_TRAIT[s]?.tendency ?? ''
    if (!trait.startsWith(name)) bad.push({ stem: s, fromTable: name, fromTrait: trait })
  }
  return bad
}

/** 관계 대상이 짝끼리 같은지. 비겁만 다른 것이 정상입니다 */
export function verifyGwangyePair(): string[] {
  const bad: string[] = []
  const groups: Array<[YukchinKey, YukchinKey]> = [
    ['식신', '상관'], ['편재', '정재'], ['편관', '정관'], ['편인', '정인'],
  ]
  for (const [a, b] of groups) {
    if (JSON.stringify(YUKCHIN_TABLE[a].gwangye) !== JSON.stringify(YUKCHIN_TABLE[b].gwangye)) {
      bad.push(`${a} 와 ${b} 의 관계 대상이 다릅니다`)
    }
  }
  return bad
}

