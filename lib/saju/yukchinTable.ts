function pick(list: Line[] | undefined, ctx?: SajuCtx): string[] {
  if (!list) return []
  const out: string[] = []
  for (const l of list) {
    if (typeof l === 'string') { out.push(l); continue }
    if (!l.when) { out.push(l.t); continue }
    if (ctx && l.when(ctx)) out.push(l.t)
  }
  return out
}

export function rowOf(key: string): YukchinRow | undefined {
  return YUKCHIN_TABLE[key as YukchinKey]
}

/**
 * 그 십성의 성향 줄.
 *   ctx 를 넘기면 조건이 붙은 줄은 맞을 때만 나갑니다.
 *   ctx 가 없으면 조건 줄은 통째로 빠집니다(겁주는 말이 새어 나가지 않게).
 */
export function yukchinLines(row: YukchinRow, target: Target, ctx?: SajuCtx): string[] {
  return [
    ...pick(row.say, ctx),
    ...(target === 'adult' ? pick(row.sayAdult, ctx) : []),
    ...(target === 'student' ? pick(row.sayStudent, ctx) : []),
  ]
}

/** 곁의 사람이 대할 때 — 궁합·상담사 */
export function darununLines(row: YukchinRow, ctx?: SajuCtx): string[] {
  return pick(row.daruneun, ctx)
}

/** 개운·처방 */
export function cheobangLines(row: YukchinRow, ctx?: SajuCtx): string[] {
  return pick(row.cheobang, ctx)
}

/** 관계 대상 한 줄. ★궁합에는 쓰지 마십시오 */
export function gwangyeLine(row: YukchinRow, gender: '남' | '여'): string {
  const g = row.gwangye[gender]
  return g?.length ? `${row.key} — ${g.join(', ')}` : ''
}

export interface YukchinHit {
  key: YukchinKey
  row: YukchinRow
  count: number
  /** 4자 이상이면 과다 (오행 잣대와 통일) */
  gwada: boolean
}

/** 사주에 선 십성을 개수와 함께. 많은 것부터 */
export function yukchinInSaju(saju: Pillar[]): YukchinHit[] {
  const c = ctxOf(saju)
  if (!c.dayStem) return []
  return YUKCHIN_KEYS
    .map(key => {
      const count = sipsinCount(c, key)
      return { key, row: YUKCHIN_TABLE[key], count, gwada: count >= GWADA_CNT }
    })
    .filter(h => h.count > 0)
    .sort((a, b) => b.count - a.count)
}

