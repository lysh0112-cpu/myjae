export type HapAudience = '성인' | '학생'

/** 합 이름으로 찾는다 — 예) findHap('甲己合') */
export function findHap(key: string): HapRow | undefined {
  return [...CHEONGAN_HAP, ...YUKHAP, ...SAMHAP, ...BANGHAP, ...JAHWA_GANHAP]
    .find(r => r.key === key)
}

/**
 * 나가는 줄을 고른다.
 *   ★통제는 여기서 한다. 프롬프트로 막지 않는다. (교훈 BF)
 *   ⚠️ alias(다른 이름)와 original 은 어느 경우에도 안 나갑니다.
 */
export function hapLines(key: string, who: HapAudience): string[] {
  const r = findHap(key)
  if (!r) return []
  return [...r.say, ...(who === '성인' ? r.sayAdult ?? [] : [])]
}
