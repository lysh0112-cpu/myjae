/** 천간 네 자리 — 년·월·일·시 차례. 없거나 모르면 빈 칸으로 둔다(자리는 지킨다). */
const ORDER = ['년주', '월주', '일주', '시주'] as const

export function stemSlots(saju: Pillar[]): string[] {
  return ORDER.map(p => {
    const s = saju.find(x => x.pillar === p)?.stem ?? ''
    return s && s !== '?' ? s : ''
  })
}

/** 글자 묶음이 들어 있는가. adjacent 면 이어진 자리에서만 본다. */
function findSet(slots: string[], chars: string[], adjacent: boolean): number[] | null {
  const n = chars.length
  if (adjacent) {
    for (let i = 0; i + n <= slots.length; i++) {
      const win = slots.slice(i, i + n)
      if (win.some(c => !c)) continue
      const a = [...win].sort(), b = [...chars].sort()
      if (a.every((c, k) => c === b[k])) return Array.from({ length: n }, (_, k) => i + k)
    }
    return null
  }
  const used: number[] = []
  for (const ch of chars) {
    const i = slots.findIndex((s, k) => s === ch && !used.includes(k))
    if (i < 0) return null
    used.push(i)
  }
  return used.sort((x, y) => x - y)
}

const pillarName = (i: number) => ORDER[i].replace('주', '간')

export interface ByeongjonHit {
  key: string
  row: ByeongjonRow
  /** 어느 자리에서 걸렸나 (년간·월간·일간·시간) */
  pillars: string[]
  /** 실제로 나란히 붙어 있었나 */
  adjacent: boolean
}

/** 사주에서 병존을 찾는다 */
export function findByeongjon(saju: Pillar[]): ByeongjonHit[] {
  const slots = stemSlots(saju)
  const hits: ByeongjonHit[] = []
  for (const row of BYEONGJON) {
    const need = row.adjacent ?? REQUIRE_ADJACENT
    const at = findSet(slots, row.chars, need)
    if (!at) continue
    const side = at.every((v, k) => k === 0 || v === at[k - 1] + 1)
    hits.push({ key: row.key, row, pillars: at.map(pillarName), adjacent: side })
  }
  return hits
}

export interface ComboHit {
  key: string
  row: ComboRow
  pillars: string[]
}

/** 벽갑인정·복덕수기·금수쌍청을 찾는다 */
export function findCombo(saju: Pillar[]): ComboHit[] {
  const slots = stemSlots(saju)
  const hits: ComboHit[] = []
  for (const row of COMBO) {
    const at = findSet(slots, row.need, row.adjacent)
    if (at) hits.push({ key: row.key, row, pillars: at.map(pillarName) })
  }
  return hits
}

/** 화면에 낼 말 한 줄 */
export function sayOf(
  row: { say: string; sayStudent?: string },
  target: 'student' | 'adult',
): string {
  return target === 'student' ? (row.sayStudent ?? row.say) : row.say
}

/**
 * 통변 재료.
 * ★original 을 절대 섞지 않는다. 재료에 있으면 AI가 꺼내 쓴다. (교훈 BF)
 */
export function reasonsOf(saju: Pillar[], target: 'student' | 'adult'): string[] {
  const out: string[] = []
  for (const h of findByeongjon(saju)) {
    const where = h.pillars.join('·')
    const yeok = h.row.yeokma ? ` [역마 ${h.row.yeokma}]` : ''
    const jobs = h.row.jobsSay ? ` (교재가 든 자리: ${h.row.jobsSay})` : ''
    out.push(`${h.row.key} 병존 (${where})${yeok} — ${sayOf(h.row, target)}${jobs}`)
  }
  for (const c of findCombo(saju)) {
    out.push(`${c.row.key} (${c.pillars.join('·')}) — ${sayOf(c.row, target)}`)
  }
  // 지지 병존 (교재 76~77쪽)
  for (const h of findJijiByeongjon(saju)) {
    const where = h.pillars.join('·')
    const sal = h.row.sal?.length ? ` [${h.row.sal.join('·')}]` : ''
    const jobs = h.row.jobs?.length
      ? ` (교재가 든 직업: ${h.row.jobs.join('·')})`
      : h.row.jobsSay ? ` (교재가 든 자리: ${h.row.jobsSay})` : ''
    out.push(`${h.row.key} 병존 (${where})${sal} — ${sayOf(h.row, target)}${jobs}`)
  }
  return out
}

