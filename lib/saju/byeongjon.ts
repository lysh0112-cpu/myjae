/** 지지 네 자리 — 년·월·일·시 차례 */
export function branchSlots(saju: Pillar[]): string[] {
  return ORDER.map(p => {
    const b = saju.find(x => x.pillar === p)?.branch ?? ''
    return b && b !== '?' ? b : ''
  })
}

export interface JijiByeongjonHit {
  key: string
  row: JijiByeongjonRow
  pillars: string[]
  adjacent: boolean
}

/** 사주에서 지지 병존을 찾는다 */
export function findJijiByeongjon(saju: Pillar[]): JijiByeongjonHit[] {
  const slots = branchSlots(saju)
  const hits: JijiByeongjonHit[] = []
  for (const row of JIJI_BYEONGJON) {
    const ch = row.key[0]
    const at = findSet(slots, [ch, ch], REQUIRE_ADJACENT)
    if (!at) continue
    const side = at.every((v, k) => k === 0 || v === at[k - 1] + 1)
    hits.push({ key: row.key, row, pillars: at.map(i => ORDER[i].replace('주', '지')), adjacent: side })
  }
  return hits
}

