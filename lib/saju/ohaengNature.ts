/** 오행 차례 */
export const OHAENG_ORDER_NATURE: Ohaeng[] = ['목', '화', '토', '금', '수']

export type NatureAudience = '성인' | '학생'

/**
 * 단점·과다로 나가는 줄.
 *   ★통제는 여기서 한다. 프롬프트로 막지 않는다. (교훈 BF)
 *   학생에게는 이성·부부·집안 이야기가 안 나갑니다.
 */
export function weaknessLines(el: Ohaeng, who: NatureAudience): string[] {
  const row = OHAENG_NATURE[el]
  return [...row.weakness, ...(who === '성인' ? row.weaknessAdult ?? [] : [])]
}

/**
 * ★그 사람을 어떻게 대할 것인가.
 *   궁합에서는 "상대를 이렇게 대하십시오" 로,
 *   상담사 화면에서는 "이 손님은 이렇게 대하십시오" 로 쓸 수 있습니다.
 */
export function handlingLines(el: Ohaeng): string[] {
  return OHAENG_NATURE[el].handling
}

/** 천간·지지로 오행을 되짚는다 */
export function ohaengOfChar(ch: string): Ohaeng | null {
  for (const el of OHAENG_ORDER_NATURE) {
    const r = OHAENG_NATURE[el]
    if (r.stems.includes(ch) || r.branches.includes(ch)) return el
  }
  return null
}
