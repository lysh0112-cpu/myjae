//
//  ★2026-08-02 신설 — 프리미엄 궁합 설계 확정본 4장
//
//  [왜 필요한가]
//    교재와 코드에는 이런 말이 «살아 있습니다» —
//      "부부간의 갈등이 온다(각방, 이혼)"        (yukchinGroup 219)
//      "배우자궁이라 부부 불화, 별거, 이혼수"     (yukchinRule 415)
//      "日支가 沖을 하면 100% 부정적이다"          (교재 121쪽)
//      "재성 기신일 경우 악처, 부부 불화수"        (교재 233쪽)
//      "사건 사고, 구설수, 이별수, 암 발생 조심"   (교재 95쪽)
//    ★이것이 그대로 재료로 나가면 AI 가 그대로 풉니다.
//      관계를 보러 오신 두 분께 드릴 말이 아닙니다.
//
//  [실측 2026-08-02]  지금 궁합 재료(7,646자)에 「헤어짐」이 «실제로» 나가고 있습니다.
//    "형충파해가 겹치면 뜻밖의 일과 구설, 헤어짐을 조심하시고"
//
//  ★[방식]  «지우지» 않고 «바꿔» 줍니다.
//    ⚠️ 지우면 뜻까지 사라져 AI 가 빈 곳을 «지어냅니다».
//    ⚠️⚠️ 낱말만 막으면 «멀쩡한 말» 까지 걸립니다. 실측에서 셋이 그랬습니다 —
//       · "명식(팔자): 戊辰…"            ← 명식을 가리키는 말
//       · "위기 속에서도 탈출구를 찾아내는" ← 좋은 뜻
//       · "이런 말을 절대 그대로 쓰지 마세요 (예: 배신수…)" ← ★금지 지시문 «안» 의 예시
//       ⇒ 그래서 «문맥이 있는 구절» 로 바꾸고, 남는 낱말만 좁게 봅니다.
//
//  ★이 방식은 yukchinGroup.ts 머리말(교훈 CA)이 이미 쓰던 것입니다 —
//    127쪽 단명·자살, 129쪽 성범죄, 131쪽 낙태를 «담지 않은» 기록.
//    그 그물을 궁합까지 넓히는 것입니다.

/** 바꿔 줄 짝 — ★긴 것부터 걸리게 «순서대로» 둡니다 */
const REPLACE: Array<[RegExp, string]> = [
  // ── 헤어짐·이혼 갈래 ──────────────────────────────────────────
  [/구설,\s*헤어짐을 조심하시고/g, '구설이 따를 수 있으니 말을 아끼시고'],
  [/부부간의 갈등이 온다\s*\(각방,\s*이혼\)/g,
    '가까울수록 서로 물러서기 어려워 다툼이 오래갈 수 있다'],
  [/각방[·,\s]*별거[·,\s]*헤어짐이 따를 수 있습니다/g,
    '함께 있는 시간이 줄어들 수 있습니다'],
  [/부부 불화,?\s*별거,?\s*이혼수가 있다/g, '서로 부딪히기 쉬운 자리다'],
  [/이혼\s*가능성이?\s*(크다|있다)/g, '서로 부딪히기 쉬운 자리다'],
  [/이별수가?\s*있다/g, '거리가 벌어지기 쉽다'],
  [/이별수/g, '거리가 벌어지는 일'],
  [/이혼수/g, '크게 부딪히는 일'],
  [/각방/g, '따로 지내는 시간'],
  [/이혼하고 재혼/g, '인연이 한 번 바뀌'],
  [/(별거|파혼|사별|이혼)/g, '큰 변화'],
  [/헤어짐/g, '거리가 벌어지는 일'],

  // ── 배우자를 «깎는» 말 (교재 233쪽) ───────────────────────────
  [/악처를?\s*만난다/g, '배우자와 부딪히기 쉽다'],
  [/악처/g, '서로 힘든 사이'],
  [/백수이거나/g, '자리를 잡기까지 시간이 걸리거나'],
  [/남편이 무능하고 덕이 없다/g, '남편에게 기대기보다 스스로 서는 결이다'],
  [/배우자덕이 없다/g, '배우자 자리가 비어 있는 결이다'],
  [/배우자\s*인연이 박하다/g, '배우자 자리가 비어 있는 결이다'],
  [/(의처증|의부증)/g, '서로를 향한 마음이 지나치게 조여드는 일'],
  [/음란하다/g, '끌림이 아주 강하다'],

  // ── 「100% 부정」 같은 단정 (교재 121쪽 · 238쪽 「단식 판단 금지」) ──
  [/100%\s*부정적이다/g, '많이 흔들리는 자리다'],
  [/부정적이다/g, '살펴야 할 자리다'],
  [/부정적으로 본다/g, '살펴야 할 자리로 본다'],

  // ── 몸·목숨에 관한 것 (교훈 CA — 우리는 의료인이 아닙니다) ──────
  [/암\s*발생\s*조심/g, '몸을 살펴 주시고'],
  [/단명\s*사주(이다|다)?/g, '몸을 특히 아껴야 하는 결이다'],
  [/단명/g, '몸을 아껴야 하는 결'],
  [/폭력성\s*있는 사람이 된다/g, '기운이 거칠게 나갈 수 있다'],
  [/폭력성/g, '거친 기운'],
  [/(자살|자해)/g, '마음이 크게 무너지는 일'],
  [/(불임|낙태)/g, '자녀를 기다리는 일'],

  // ── 도화 갈래 — 「바람기」를 그대로 쓰지 않습니다 ─────────────
  [/바람기가?\s*있다/g, '사람을 끌어당기는 결이 밖으로 향한다'],
  [/바람기/g, '밖으로 향하는 끌림'],
  [/(외도|불륜)/g, '마음이 밖으로 향하는 일'],
  [/이성\s*문제/g, '사람 사이의 일'],

  // ── 사람을 깎는 말 ────────────────────────────────────────────
  [/독불장군에 고집불통입니다/g, '뜻이 뚜렷하고 스스로 정하는 편입니다'],
  [/고집불통/g, '뜻이 아주 뚜렷함'],
  [/배신을?\s*당할 수 있으며/g, '믿었던 자리에서 서운함이 올 수 있으며'],
  [/배신수/g, '서운한 일'],
  [/원수충/g, '가장 세게 부딪히는 자리'],
  [/기생,?\s*스님\s*팔자/g, '남다른 길을 가는 결'],
  [/마마(보이|걸)\s*스타일로?/g, '곁의 사람에게 기대는 결로'],
  [/현모양처/g, '집안을 든든히 세우는 결'],
]

/**
 * ★남은 낱말 — «문맥을 봐야» 하는 것들.
 *   ⚠️ 그대로 막으면 멀쩡한 말이 걸립니다. 실측에서 셋이 그랬습니다.
 *   ⇒ «앞뒤에 이런 말이 함께 있으면» 봐 줍니다.
 */
const CONTEXT_OK: Array<{ word: string; okNear: RegExp; why: string }> = [
  { word: '팔자', okNear: /명식\s*\(팔자\)|사주\s*팔자|여덟\s*글자/, why: '명식을 가리키는 말' },
  { word: '위기', okNear: /위기\s*속에서도|위기를\s*(넘|이겨|기회)/, why: '좋은 뜻으로 쓰인 자리' },
  { word: '배신', okNear: /절대\s*그대로\s*쓰지|쓰지\s*마세요|예\s*:/, why: '금지 지시문 안의 예시' },
]

/** 문맥을 봐도 남으면 «반드시» 걸러야 하는 낱말 */
const HARD_BAN = [
  '이혼', '별거', '각방', '헤어짐', '파혼', '사별',
  '악처', '무능', '단명', '자살', '불임', '낙태',
  '음란', '의처증', '의부증', '바람기', '외도', '불륜',
]

/**
 * 재료 한 덩이를 다듬습니다.
 *
 * ⚠️⚠️ 이 함수를 «지나지 않고» 프롬프트로 나가는 길을 만들지 마십시오.
 *    검사가 그것을 셉니다.
 */
export function guardTone(text: string): string {
  let out = text
  for (const [re, to] of REPLACE) out = out.replace(re, to)
  return out
}

/** 남아 있는 금지어 — 문맥이 괜찮은 것은 빼고 셉니다 */
export function findBanned(text: string): Array<{ word: string; around: string }> {
  const found: Array<{ word: string; around: string }> = []
  for (const w of HARD_BAN) {
    let i = text.indexOf(w)
    while (i >= 0) {
      const around = text.slice(Math.max(0, i - 30), i + 30).replace(/\n/g, ' ')
      const ok = CONTEXT_OK.find(c => c.word === w && c.okNear.test(around))
      if (!ok) found.push({ word: w, around })
      i = text.indexOf(w, i + 1)
    }
  }
  return found
}

