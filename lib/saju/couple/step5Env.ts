//    ⛔ 점수·별점을 내지 «않습니다». 교재에 궁합 배점표가 «없습니다».
//       ★무게는 «말하는 차례와 길이» 로 줍니다.
//
//  ══ 부품 재사용 (교훈 E — 만들기 전에 grep) ══
//    ✅ monthSeasonMatch (coupleFilterV1) — 두 사람 월지 «계절» 짝. ★이미 있습니다
//       ⇒ 여기서는 «지지 관계(합·충 등)» 만 봅니다. 계절은 그쪽이 맡습니다.

/** 지지 여섯 짝 — 육합 (교재 「코드가 맞는 사람끼리의 사적인 결합」) */
const YUKHAP: Record<string, string> = {
  子: '丑', 丑: '子', 寅: '亥', 亥: '寅', 卯: '戌', 戌: '卯',
  辰: '酉', 酉: '辰', 巳: '申', 申: '巳', 午: '未', 未: '午',
}

/** 지지 충 */
const CHUNG: Record<string, string> = {
  子: '午', 午: '子', 丑: '未', 未: '丑', 寅: '申', 申: '寅',
  卯: '酉', 酉: '卯', 辰: '戌', 戌: '辰', 巳: '亥', 亥: '巳',
}

/**
 * 삼합 — 세 글자 묶음.
 * ⚠️ 두 사람은 «두 글자» 뿐이라 «세 글자 완성» 이 될 수 없습니다.
 *    ★교재가 두 글자 짝을 셋으로 갈라 부릅니다 —
 *      준삼합 (生+旺) · 반합 (旺+墓) · 가합 (生+墓)
 *    ⚠️ 「삼합」이라 부르지 «마십시오». 세 글자가 아니면 다른 이름입니다.
 */
const SAMHAP: Array<{ birth: string; king: string; grave: string; el: string }> = [
  { birth: '申', king: '子', grave: '辰', el: '수' },
  { birth: '亥', king: '卯', grave: '未', el: '목' },
  { birth: '寅', king: '午', grave: '戌', el: '화' },
  { birth: '巳', king: '酉', grave: '丑', el: '금' },
]

/** 방합 — 계절 묶음. 역시 두 글자면 «반» 입니다 */
const BANGHAP: Array<{ set: string[]; el: string; season: string }> = [
  { set: ['寅', '卯', '辰'], el: '목', season: '봄' },
  { set: ['巳', '午', '未'], el: '화', season: '여름' },
  { set: ['申', '酉', '戌'], el: '금', season: '가을' },
  { set: ['亥', '子', '丑'], el: '수', season: '겨울' },
]

export type PairKind =
  | '육합' | '준삼합' | '반합' | '가합' | '방합(반)' | '충' | '무관'

export interface PairResult {
  kind: PairKind
  /** ★강도 — 교재 「방합 > 삼합 > 육합·천간합」 */
  power: 3 | 2 | 1 | 0
  /** 손님께 드릴 말 */
  say: string
}

/**
 * 두 지지를 맞대어 «관계 이름과 뜻» 을 냅니다.
 *
 * ⚠️⚠️ 등급(A·B·C·D)을 내지 «않습니다».
 *    ★49쪽 조견표는 «운 대입» 표이고, 그 등급의 «뜻이 교재에 없습니다».
 * ★대칭입니다 — 두 사람 사이는 «서로» 이므로 (a,b)와 (b,a)가 같아야 합니다.
 */
export function judgeBranchPair(a: string, b: string): PairResult {
  if (!a || !b) return { kind: '무관', power: 0, say: '' }

  // ══════════════════════════════════════════════════════════════
  //  ★차례가 중요합니다 — «육합» 을 먼저 봅니다.
  //
  //  🔴 [2026-08-02 — 처음에 잘못 지었던 것]
  //    방합을 먼저 보게 했더니 «子丑» 이 「방합(반)」으로 잡혔습니다.
  //    ★교재는 子丑을 «육합» 의 대표로 듭니다 —
  //      "子丑合: 六合은 코드가 맞는 사람끼리의 사적인 결합"
  //    ⚠️ 겹치는 짝은 «子丑 · 午未» 둘뿐입니다. 둘 다 교재가 «육합» 이라 부릅니다.
  //  ⇒ ★교재가 이름 붙인 쪽을 따릅니다. 강도(방합>삼합>육합)는 «이름을 정한 뒤» 의 이야기입니다.
  // ══════════════════════════════════════════════════════════════

  // ── 육합 — 교재 「코드가 맞는 사람끼리의 사적인 결합」 ──
  if (YUKHAP[a] === b) {
    return {
      kind: '육합', power: 2,
      say: '두 분의 자리가 «육합» 으로 맺어집니다. '
        + '교재는 이것을 «코드가 맞는 사람끼리의 사적인 결합» 이라 부릅니다. '
        + '따로 애쓰지 않아도 무난히 어울리는 사이예요.',
    }
  }

  // ── 방합(반) — 교재 「강도는 三合보다 方局이 더 강하다」 ──
  for (const g of BANGHAP) {
    if (a !== b && g.set.includes(a) && g.set.includes(b)) {
      return {
        kind: '방합(반)', power: 3,
        say: `두 분의 자리가 «같은 계절»(${g.season})을 이룹니다. `
          + `세 글자가 다 모인 것은 아니라 «반» 이지만, 바라보는 쪽이 같은 결이에요.`,
      }
    }
  }

  // ── 삼합의 두 글자 — 준삼합 / 반합 / 가합 ──
  for (const g of SAMHAP) {
    const set = [g.birth, g.king, g.grave]
    if (a === b || !set.includes(a) || !set.includes(b)) continue
    const has = (x: string) => a === x || b === x
    if (has(g.birth) && has(g.king)) {
      return {
        kind: '준삼합', power: 3,
        say: '두 분의 자리가 «시작과 한창» 으로 맞물립니다. '
          + '함께 무언가를 벌일 때 힘이 잘 붙는 결이에요.',
      }
    }
    if (has(g.king) && has(g.grave)) {
      return {
        kind: '반합', power: 2,
        say: '두 분의 자리가 «한창과 마무리» 로 맞물립니다. '
          + '벌인 것을 잘 거두는 결입니다.',
      }
    }
    return {
      kind: '가합', power: 1,
      // ⚠️ 교재 — "가합은 시작은 잘하나 실천을 잘 안 하고 마무리 능력이 부족하다"
      //    ★그대로 옮기면 깎는 말이 됩니다. 뜻만 살립니다.
      say: '두 분의 자리가 «시작과 마무리» 로 이어집니다. '
        + '가운데를 이어 줄 무언가가 있으면 훨씬 잘 굴러가는 결이에요.',
    }
  }

  // ── 충 ──
  if (CHUNG[a] === b) {
    return {
      kind: '충', power: 1,
      // ⚠️ 「충 = 나쁨」이 아닙니다. 교재 121·263쪽 "時支가 沖을 하면 50%는 긍정적"
      say: '두 분의 자리가 «마주 서는» 짝입니다. '
        + '보는 쪽이 정반대라 부딪히기도 하지만, 그만큼 서로가 못 보는 것을 봐 줍니다.',
    }
  }

  return { kind: '무관', power: 0, say: '' }
}

export interface EnvInput {
  aName: string
  bName: string
  aMonth: string
  bMonth: string
  aYear: string
  bYear: string
}

export interface EnvResult {
  /** 월지 × 월지 — 삶에서 중히 여기는 것 */
  month: PairResult
  /** 년지 × 년지 — 집안·바깥 자리 (★띠) */
  year: PairResult
  lines: string[]
  solution: string | null
}

/**
 * 5단계 — 두 분이 세상과 만나는 자리.
 *
 * ★말하는 차례가 «무게» 입니다 (교재 「月支가 총사령관」).
 *    월지를 «먼저», 년지를 «가볍게» 뒤에.
 * ⚠️ 계절 짝(찰떡궁합)은 여기서 말하지 «않습니다» —
 *    monthSeasonMatch 가 이미 4단계 언저리에서 말합니다. 두 번 말하지 마십시오.
 */
export function judgeEnv(x: EnvInput): EnvResult {
  const month = judgeBranchPair(x.aMonth, x.bMonth)
  const year = judgeBranchPair(x.aYear, x.bYear)
  const lines: string[] = []
  let solution: string | null = null

  // ── ① 월지 — 삶에서 중히 여기는 것 (교재 「그릇이 나오는 자리」) ──
  if (month.kind !== '무관') {
    lines.push(`두 분이 «삶에서 중히 여기는 것»(월지)을 보면, ${month.say}`)
    if (month.kind === '충') {
      lines.push('같은 일을 두고도 첫 대답이 다를 때가 많으실 거예요. '
        + '한 분이 넓히려 하면 한 분은 다지려 하십니다.')
      solution = '다르다는 것이 어긋난다는 뜻은 아닙니다. '
        + '둘 다 벌이기만 하면 뒤가 비고, 둘 다 지키기만 하면 앞이 막혀요. '
        + '★큰 결정 앞에서는 「원래 결이 다르다」는 것을 먼저 떠올리시면 훨씬 수월합니다.'
    } else if (month.power >= 2) {
      solution = '삶의 방향이 비슷하니 큰 다툼은 적으실 거예요. '
        + '다만 둘 다 같은 쪽만 보게 되니, 가끔 «다른 눈» 을 가진 사람의 말을 들어 두시면 좋습니다.'
    }
  } else {
    lines.push('두 분이 «삶에서 중히 여기는 것»(월지)은 서로 얽히지도 부딪히지도 않습니다. '
      + '각자의 자리를 지키면서 함께 가는 결이에요.')
  }

  // ── ② 년지 — 집안·바깥 자리 (★가볍게) ──
  if (year.kind !== '무관') {
    lines.push(`집안 어른들과 주변 사람들의 자리(년지)는 — ${year.say}`)
  } else {
    lines.push('집안 어른들과 주변 사람들의 자리(년지)는 데면데면한 편입니다. '
      + '크게 부딪히지도, 아주 가깝지도 않은 결이에요. '
      + '서로의 가족에게 억지로 녹아들려 애쓰지 않으셔도 됩니다.')
  }

  // ── ③ ★띠 궁합 안내 — 손님이 가장 잘 아는 자리 ──
  //    ⚠️ 미리 말해 두지 않으면 「띠로 본 것과 다르다」는 물음이 반드시 옵니다.
  lines.push('★흔히 말하는 «띠 궁합» 이 바로 이 년지 자리입니다. '
    + '그것은 «집안과 바깥의 자리» 를 보는 것이고, '
    + '두 분 사이의 실제 결은 앞의 «태어난 날» 이 말해 줍니다. '
    + '띠로 본 것과 다르게 느껴지셔도 놀라지 마십시오.')

  return { month, year, lines, solution }
}

/** ★AI 재료로 넘길 한 덩이 */
export function envBlock(x: EnvInput): string {
  const r = judgeEnv(x)
  const out: string[] = ['[함께 살아가는 결 — 월지·년지]']
  out.push(`- 월지  ${x.aName} ${x.aMonth} ↔ ${x.bName} ${x.bMonth} : ${r.month.kind}`)
  out.push(`- 년지  ${x.aName} ${x.aYear} ↔ ${x.bName} ${x.bYear} : ${r.year.kind}`)
  out.push('※ ★월지를 «먼저», 년지를 «가볍게» 뒤에 말하세요 (교재 「月支가 총사령관」).')
  out.push('※ ★「겉궁합」이라 부르지 마세요. 교재에 없는 말입니다.')
  out.push('※ 등급이나 점수를 매기지 마세요. 교재에 궁합 배점표가 없습니다.')
  for (const l of r.lines) out.push(`  ${l}`)
  if (r.solution) out.push(`  → ${r.solution}`)
  return out.join('\n')
}
