//       손님이 「겉은 좋은데 속은 나쁘다」로 읽습니다.
//    ⛔⛔ 49쪽 조견표(jijiGrade · jijiPairText)를 «쓰지 않습니다».
//       ★그 표의 머리말은 "대운이나 세운을 일단 月支에 대입해라" 입니다 —
