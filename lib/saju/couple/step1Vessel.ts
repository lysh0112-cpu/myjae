export type Ohaeng = '목' | '화' | '토' | '금' | '수'
export type Status = '극신약' | '신약' | '중화' | '신강' | null

export interface VesselPerson {
  name: string
  status: Status
  season: '봄' | '여름' | '가을' | '겨울'
  /** 이분께 필요한 기운 */
  needEl: Ohaeng
  /** 그것을 «조후» 로 봤는가 «억부» 로 봤는가 */
  needFrom: '조후' | '억부'
}

export type VesselCross =
  | '둘 다 뚜렷'      // 신강 × 신강 — 교재 142·123쪽
  | '뚜렷과 헤아림'   // 신강 × 신약 — ★교재 142쪽 «권장»
  | '둘 다 헤아림'    // 신약 × 신약 — ⛔ 교재에 «없음». 판정하지 않습니다
  | '고름'

export interface VesselResult {
  cross: VesselCross
  lines: string[]
  solution: string | null
}

/** 신강 쪽인가 (중화는 «어느 쪽도 아님») */
function isStrong(s: Status): boolean {
  return s === '신강'
}
/** 신약 쪽인가 — ★극신약도 여기 듭니다 */
function isWeak(s: Status): boolean {
  return s === '신약' || s === '극신약'
}

/** 각자의 «그릇» 을 한 줄로 */
function vesselSay(p: VesselPerson): string {
  if (isStrong(p.status)) {
    // 교재 142쪽 — 자신감·배짱·추진력·주관
    return `${p.name}님은 «뜻이 뚜렷하고 잘 흔들리지 않는» 결을 타고나셨습니다. `
      + '남이 짜 놓은 판을 따르기보다 스스로 판을 만드는 쪽에서 힘이 나는 분이에요. '
      + '한번 마음을 먹으면 끝까지 밀고 가시는 편입니다.'
  }
  if (p.status === '극신약') {
    // ⚠️ 126쪽 "대단히 조심해야 한다" 를 그대로 쓰지 «않습니다».
    //    ★「뿌리가 얕다」를 「곁을 살피는 결」로 옮깁니다.
    return `${p.name}님은 «둘레를 먼저 살피는» 결이 아주 짙습니다. `
      + '혼자 밀고 나가기보다 사람과 자리를 헤아리며 가시는 분이에요. '
      + '그만큼 놓치는 것이 적지만, 기댈 곳이 있을 때 훨씬 편안해지십니다.'
  }
  if (p.status === '신약') {
    // ⚠️ 143쪽 「마마보이·마마걸」은 그대로 쓰지 «않습니다».
    return `${p.name}님은 «곁을 헤아리며 가는» 결입니다. `
      + '먼저 나서지 않는 대신 나온 이야기를 오래 곱씹고 빠진 것을 찾아내십니다. '
      + '다만 사람의 말에 마음이 잘 움직이시는 편이에요.'
  }
  return `${p.name}님은 «어느 한쪽으로 치우치지 않은» 결입니다. `
    + '나설 자리와 물러설 자리를 스스로 가리시는 분이에요.'
}

/** 각자의 «온도» 를 한 줄로 (교재 232쪽 2번 「조후에서는 水火가 가장 중요」) */
function tempSay(p: VesselPerson): string {
  if (p.season === '겨울') {
    return `${p.name}님은 «겨울» 에 나신 결이라 바탕이 차분하고 서늘합니다. `
      + '★따뜻한 기운이 곁에 있을 때 마음이 놓이시는 분이에요.'
  }
  if (p.season === '여름') {
    return `${p.name}님은 «여름» 에 나신 결이라 바탕이 밝고 뜨겁습니다. `
      + '★시원하게 식혀 주는 자리가 있을 때 마음이 편해지시는 분이에요.'
  }
  // ⚠️ 봄·가을은 교재가 「조후가 온화하다」고 봅니다 (calcJohu 가 null 을 냅니다)
  return `${p.name}님은 «${p.season}» 에 나셔서 마음의 온도가 온화한 편입니다. `
    + '차갑지도 뜨겁지도 않아 어느 자리에 놓여도 크게 부대끼지 않으십니다.'
}

/**
 * 1단계 — 두 분의 그릇과 온도.
 *
 * ★교재 142쪽 "신강 사주의 배우자는 «신약 사주랑 만나는 게 좋다»" 가 이 단계의 뼈대입니다.
 * ⚠️ 「둘 다 신약」은 «판정하지 않습니다» — 교재에 없습니다.
 */
export function judgeVessel(a: VesselPerson, b: VesselPerson): VesselResult {
  const lines: string[] = []
  let solution: string | null = null

  // ── ① 각자의 그릇 ──
  lines.push(vesselSay(a))
  lines.push(vesselSay(b))

  // ── ② 각자의 온도 ──
  lines.push(tempSay(a))
  lines.push(tempSay(b))

  // ── ③ ★온도가 서로를 눅여 주는가 (교재 232쪽 2번 · 140쪽) ──
  const opposite =
    (a.season === '겨울' && b.season === '여름') ||
    (a.season === '여름' && b.season === '겨울')
  if (opposite) {
    const cold = a.season === '겨울' ? a : b
    const hot = a.season === '여름' ? a : b
    lines.push(`★그리고 두 분의 온도가 «서로 반대» 입니다. `
      + `${cold.name}님의 서늘함을 ${hot.name}님이 데워 주고, `
      + `${hot.name}님의 열기를 ${cold.name}님이 식혀 주십니다. `
      + `교재가 궁합에서 «가장 좋게» 보는 자리 가운데 하나예요.`)
  }

  // ── ④ ★그릇의 교차 (교재 142·123쪽) ──
  const aS = isStrong(a.status), bS = isStrong(b.status)
  const aW = isWeak(a.status), bW = isWeak(b.status)

  let cross: VesselCross = '고름'
  if (aS && bS) {
    cross = '둘 다 뚜렷'
    lines.push('두 분 다 «뜻이 뚜렷하고 물러서기 어려운» 결을 지니셨습니다. '
      + '서로를 존중하시는 만큼, 부딪히면 오래갈 수 있어요.')
    // ★123쪽 — 이 단계의 보석. 불화로 끝내지 않습니다.
    lines.push('★교재는 이런 두 분이 «잘 지내시면» 인품과 마음공부가 깊은 분들이라고 말합니다. '
      + '쉽지 않은 만큼, 잘 지내시는 그 자체가 두 분의 힘입니다.')
    solution = '다툼이 커질 것 같을 때 «그 자리에서 결론 내지 않기» 를 '
      + '두 분의 약속으로 정해 두시면 좋습니다. 하루만 지나도 훨씬 가벼워집니다.'
  } else if ((aS && bW) || (bS && aW)) {
    cross = '뚜렷과 헤아림'
    const lead = aS ? a : b
    const follow = aS ? b : a
    lines.push(`${lead.name}님이 «앞서 가는» 결이고 ${follow.name}님이 «헤아리며 걷는» 결입니다. `
      + '★교재는 이런 짝을 좋게 봅니다. 둘 다 앞서려 하면 서로 물러서지 못해 부딪히고, '
      + '둘 다 헤아리기만 하면 아무도 첫걸음을 떼지 못하기 때문이에요.')
    solution = `큰일을 정하실 때는 ${lead.name}님이 먼저 말을 꺼내시고, `
      + `${follow.name}님이 «하루쯤 두고» 답하시면 훨씬 수월합니다. `
      + '그 자리에서 바로 답을 구하시면 헤아리는 결이 충분히 나오지 못합니다.'
  } else if (aW && bW) {
    cross = '둘 다 헤아림'
    // ⛔⛔ 교재에 이 조합에 대한 말이 «없습니다». 판정하지 «않습니다».
    //    ★143쪽의 개인 특성을 «나란히 놓기만» 합니다.
    lines.push('두 분 다 «곁을 헤아리며 가는» 결입니다. '
      + '서로 밀지 않으시니 다툼이 적고, 상대의 기분을 빨리 알아채십니다.')
    solution = '다만 두 분 다 먼저 말을 꺼내지 않으시면 정해야 할 것이 밀립니다. '
      + '★「이번 건은 누가 정할지」를 먼저 나누어 두시면 훨씬 수월합니다.'
  } else {
    lines.push('두 분의 결이 한쪽으로 치우치지 않아, 자리에 따라 이끄는 쪽이 자연스레 바뀝니다.')
  }

  return { cross, lines, solution }
}

/** ★AI 재료로 넘길 한 덩이 */
export function vesselBlock(a: VesselPerson, b: VesselPerson): string {
  const r = judgeVessel(a, b)
  const out: string[] = ['[두 분은 어떤 분인가 — 그릇과 온도]']
  out.push(`- ${a.name} : ${a.status ?? '판정 못 함'} · ${a.season}생 · 필요한 기운 ${a.needEl}(${a.needFrom})`)
  out.push(`- ${b.name} : ${b.status ?? '판정 못 함'} · ${b.season}생 · 필요한 기운 ${b.needEl}(${b.needFrom})`)
  out.push(`- 그릇의 교차 : ${r.cross}`)
  out.push('※ ★「극신강」이라는 말을 쓰지 마세요. 교재에 없습니다 (신강·신약·극신약·중화).')
  // ⚠️⚠️ 금지어를 «여기 적지 마십시오».
  //   🔴 2026-08-02 — 「고집불통」이라 적었더니 guardTone 이 그것을 «바꿔» 버려
  //      "「고집불통」 같은 말은 금지" 가 "「뜻이 아주 뚜렷함」 같은 말은 금지" 로 나갔습니다.
  //      ⇒ 뜻이 통째로 뒤집혔습니다. 오늘 같은 함정을 «다섯 번째» 밟았습니다.
  //   ★금지어 목록은 toneGuard.BAN_NOTE «한 곳» 에만 둡니다.
  //     여기서는 «써야 할 말» 만 알려 줍니다.
  out.push('※ ★사람을 깎지 말고 «결» 로 옮겨 말하세요. 금지어 목록은 앞의 안내를 따르십시오.')
  out.push('※ ★이 대목은 «각자가 어떤 분인가» 만 말하세요. 만나서 어떻게 되는지는 뒤에서 다룹니다.')
  for (const l of r.lines) out.push(`  ${l}`)
  if (r.solution) out.push(`  → ${r.solution}`)
  return out.join('\n')
}
