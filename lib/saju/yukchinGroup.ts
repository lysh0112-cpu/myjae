// ── 조건 잴 잔손 ────────────────────────────────────────────────
//   ★yukchinTable 의 pairCount 를 그대로 씁니다. 부품을 새로 만들지 않습니다.

const manyPair = (p: YukchinPair) => (c: SajuCtx) => pairCount(c, p) >= GWADA_CNT
const nonePair = (p: YukchinPair) => (c: SajuCtx) => pairCount(c, p) === 0
/** 신강 쪽인가 — 비겁 + 인성이 넉넉한가 (교재 126쪽 정의) */
const singang = (c: SajuCtx) => pairCount(c, '비겁') + pairCount(c, '인성') >= 4
/** 재다신약 — 재성이 과다하고 비겁·인성이 모자란가 */
const jaedaSinyak = (c: SajuCtx) => pairCount(c, '재성') >= GWADA_CNT && !singang(c)
/** 신왕관왕 — 비겁·인성이 넉넉하면서 관성도 선 경우 */
const sinwangGwanwang = (c: SajuCtx) => singang(c) && pairCount(c, '관성') >= 2
/** 관성이 튼튼한가 */
const gwanTight = (c: SajuCtx) => pairCount(c, '관성') >= 2

