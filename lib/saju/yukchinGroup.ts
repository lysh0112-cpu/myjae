function pick(list: Line[] | undefined, ctx?: SajuCtx): string[] {
  if (!list) return []
  const out: string[] = []
  for (const l of list) {
    if (typeof l === 'string') { out.push(l); continue }
    if (!l.when) { out.push(l.t); continue }
    if (ctx && l.when(ctx)) out.push(l.t)
  }
  return out
}

export function groupOf(pair: string): YukchinGroupRow | undefined {
  return YUKCHIN_GROUP[pair as YukchinPair]
}

export interface GroupHit {
  key: YukchinPair
  row: YukchinGroupRow
  count: number
  /** 4자 이상 */
  gwada: boolean
  /** 0자 */
  none: boolean
}

/** 다섯 짝을 개수와 함께. 많은 것부터 */
export function groupsInSaju(saju: Pillar[]): GroupHit[] {
  const c = ctxOf(saju)
  if (!c.dayStem) return []
  return PAIRS
    .map(key => {
      const count = pairCount(c, key)
      return { key, row: YUKCHIN_GROUP[key], count, gwada: count >= GWADA_CNT, none: count === 0 }
    })
    .sort((a, b) => b.count - a.count)
}

/**
 * ★재료용 — 과다한 짝과 없는 짝만. jaryoPick 이 부르는 자리.
 *
 *   과다(4자 이상)  → 많을 때 단점 + 편중 부작용 + 개운법
 *   없음(0자)       → 없을 때
 *   그 밖           → 아무것도 안 냄 (보통이면 할 말이 없습니다)
 *
 * ⚠️ 편중 줄을 내보낼 때는 PYEONJUNG_CLOSING 을 **맨 마지막에** 함께 붙이십시오.
 *    withClosing: true 로 부르면 여기서 붙여 줍니다.
 */
export function groupBrief(
  saju: Pillar[],
  target: Target,
  opt: { cap?: number; 보완?: boolean; 개운?: boolean; 직업?: boolean; withClosing?: boolean } = {},
): string[] {
  const { cap = 3 } = opt
  const c = ctxOf(saju)
  if (!c.dayStem) return []
  const hits = groupsInSaju(saju)
  const out: string[] = []
  let usedPyeonjung = false

  for (const h of hits) {
    if (h.gwada) {
      usedPyeonjung = true
      const bad = [
        ...pick(h.row.manyBad, c),
        ...(target === 'adult' ? pick(h.row.manyBadAdult, c) : []),
        ...(target === 'student' ? pick(h.row.manyBadStudent, c) : []),
      ].slice(0, cap)
      const good = pick(h.row.manyGood, c).slice(0, 2)
      out.push(`${h.key}(${h.row.hanja}) 과다 ${h.count}자 — ${[...good, ...bad].join(' ')}`)
      const pj = [
        ...pick(h.row.pyeonjungBad, c),
        ...(target === 'adult' ? pick(h.row.pyeonjungBadAdult, c) : []),
        ...(target === 'student' ? pick(h.row.pyeonjungBadStudent, c) : []),
      ].slice(0, cap)
      if (pj.length) out.push(`  · 편중·혼잡: ${pj.join(' ')}`)
      if (opt.보완) {
        out.push(`  · 보완할 자리: ${h.row.bowanTargets.join('·')} — ${h.row.bowan.slice(0, 2).join(' ')}`)
      }
      if (opt.개운) {
        const g = [...pick(h.row.gaeun, c), ...(target === 'adult' ? pick(h.row.gaeunAdult, c) : [])].slice(0, 2)
        if (g.length) out.push(`  · 개운: ${g.join(' ')}`)
      }
      if (opt.직업 && h.row.jobs?.length) out.push(`  · 교재가 든 자리: ${h.row.jobs.slice(0, 6).join(' · ')}`)
    } else if (h.none) {
      const n = [
        ...pick(h.row.none, c),
        ...(target === 'adult' ? pick(h.row.noneAdult, c) : []),
      ].slice(0, cap)
      if (n.length) out.push(`${h.key}(${h.row.hanja}) 없음 — ${n.join(' ')}`)
    }
  }

  if (usedPyeonjung && opt.withClosing) out.push(...PYEONJUNG_CLOSING)
  return out
}

